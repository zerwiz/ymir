#!/usr/bin/env python3
"""doors.py — a door register for ANY directory, rendered from the tree.

Plan 115 P7/P8. The house's door register (`bin/README.md`) covers `bin/` and the backend
shelf, and stops there. Measured on 2026-10-23: `apps/` holds 405 entry points and `tools/`
11 of 13, none of them in any register — and the same subsystem's shell doors are indexed
only because they happen to live under `bin/`. A home shelf (`hodd/bin/`) has doors too.

This renders the SAME shape for any directory, so a subsystem's register is derived, not
written:

    DOORS.md    doors[n]{file,does,kind,executable,lines}

Tracked files only when the directory is inside a git work tree (`git ls-files` scoped to
it); a filesystem walk otherwise, always excluding `node_modules`, `.git`, `dist`, `build`,
`__pycache__`. Tracked-only is what makes the output reproducible from a clean checkout —
the fault `bin/gates/inventory.sh` carried until 2026-10-23.

    doors.py --root DIR [--out FILE] [--check]

Exit: 0 written/current · 1 stale or missing · 2 usage.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

VERSION = "1.0.0"
EXTS = (".sh", ".py", ".mjs", ".js", ".ts", ".tsx")
SKIP_DIRS = {"node_modules", ".git", "dist", "build", "__pycache__", ".yarn", ".venv", "venv"}


def run(cmd: list[str], cwd: Path) -> str:
    try:
        return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True).stdout
    except Exception:
        return ""


def files(root: Path) -> list[Path]:
    inside = run(["git", "rev-parse", "--is-inside-work-tree"], root).strip() == "true"
    out: list[Path] = []
    if inside:
        top = Path(run(["git", "rev-parse", "--show-toplevel"], root).strip() or root)
        try:
            relroot = root.resolve().relative_to(top.resolve()).as_posix()
        except ValueError:
            relroot = ""
        # --full-name: from a SUBDIRECTORY `git ls-files` yields paths relative to that
        # subdirectory, so a "hodd/bin/" prefix filter matched nothing (measured: 0 rows).
        for line in run(["git", "ls-files", "--full-name"], root).splitlines():
            if relroot and not line.startswith(relroot.rstrip("/") + "/"):
                continue
            p = top / line
            if p.is_file() and p.suffix in EXTS and not (set(p.parts) & SKIP_DIRS):
                out.append(p)
    else:
        for p in root.rglob("*"):
            if p.is_file() and p.suffix in EXTS and not (set(p.parts) & SKIP_DIRS):
                out.append(p)
    return sorted(out)


def first_sentence(path: Path, limit: int = 130) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").split("\n")[:20]
    except Exception:
        return "(unreadable)"
    for raw in lines:
        s = raw.strip()
        if not s or s.startswith("#!") or s.startswith(("\"\"\"", "'''")) and s.strip("\"'") == "":
            continue
        if s.startswith(("#", "//", "*", "\"\"\"", "'''")):
            s = s.lstrip("#/*'\" ").strip()
            s = s.removesuffix("\"\"\"").removesuffix("'''").strip()
            if len(s) < 4:
                continue
            return (s[: limit - 1] + "…") if len(s) > limit else s
        break
    return "(no header)"


def kind(path: Path) -> str:
    name = path.name
    if "-lib" in name or name in ("_lib.py", "lib.py"):
        return "lib"
    if path.suffix == ".py" and path.parent.name == "tests" or ".test." in name:
        return "test"
    if name.endswith((".mjs", ".js")) and ("server" in name or "gateway" in name):
        return "server"
    return "tool"


def render(root: Path) -> str:
    fs = files(root)
    rows = []
    for p in fs:
        rel = p.relative_to(root).as_posix()
        rows.append([rel, first_sentence(p), kind(p),
                     "yes" if (p.stat().st_mode & 0o111) else "no",
                     str(p.read_text(encoding="utf-8", errors="replace").count("\n") + 1)])
    counts: dict[str, int] = {}
    for r in rows:
        counts[r[2]] = counts.get(r[2], 0) + 1
    tally = ", ".join(f"{k}={v}" for k, v in sorted(counts.items(), key=lambda kv: -kv[1]))
    lines = [
        f"# DOORS — {root.name}",
        "",
        "**Generated by `bin/gates/doors.sh`. Do not hand-edit.**",
        "One row per entry point in this directory: what it is, whether it is executable, how long it is.",
        "Rendered from the tree, so it cannot rot while the gate runs (`doors.sh --check`).",
        "",
        f"doors[{len(rows)}]{{file,does,kind,executable,lines}}:",
    ]
    for r in rows:
        lines.append("  " + ",".join('"' + c.replace('"', "'") + '"' for c in r))
    lines += ["", f"**Tally.** {tally or 'no entry points'}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0 if argv else 2
    if argv[0] in ("-v", "--version"):
        print(VERSION)
        return 0
    root, out, check = Path("."), None, False
    i = 0
    while i < len(argv):
        if argv[i] == "--root" and i + 1 < len(argv):
            root = Path(argv[i + 1]).expanduser()
            i += 2
        elif argv[i] == "--out" and i + 1 < len(argv):
            out = Path(argv[i + 1]).expanduser()
            i += 2
        elif argv[i] == "--check":
            check = True
            i += 1
        else:
            print(f"doors: unknown argument {argv[i]!r}", file=sys.stderr)
            return 2
    if not root.is_dir():
        print(f"doors: {root} is not a directory", file=sys.stderr)
        return 2
    # A RELATIVE root ("tools") produced absolute files, and `relative_to` then refused
    # every one of them (measured: ValueError on the first row). One resolution, once.
    root = root.resolve()
    target = out or (root / "DOORS.md")
    body = render(root)
    if check:
        if not target.is_file():
            print(f"doors: {target} does not exist — run bin/gates/doors.sh --root {root}")
            return 1
        if target.read_text(encoding="utf-8").strip() != body.strip():
            print(f"doors: {target} is STALE — run bin/gates/doors.sh --root {root} (the register is derived)")
            return 1
        print(f'doors[1]{{register,rows}}:\n  "{target}","{len(files(root))}"')
        return 0
    target.write_text(body, encoding="utf-8")
    print(f'doors[1]{{wrote,rows}}:\n  "{target}","{len(files(root))}"')
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
