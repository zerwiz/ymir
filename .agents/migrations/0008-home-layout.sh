#!/usr/bin/env bash
# 0008-home-layout — bring an existing home into the layout Rule 21 states.
#
# Rule 21: the home has a layout, and nothing is created outside it. A fresh install
# gets that shape from the first moment; this migration gives it to a home that was
# made before the rule existed — which is every home but the newest.
#
# The faults it heals, all measured on a real operator home on 2026-10-13:
#
#   state OUTSIDE the home        ~/Documents/Ymir/state, and state inside the public repo
#                                 (ymir/.agents/state, ymir/bin/state)   -> $YMIR_HOME/state/
#   a stray hoard                 ~/hodd (created by one line of instructions) -> $YMIR_HOME/hodd/
#   companies under identity      hodd/identity/companies/<company>/ -> svartalfaheim/<company>/
#   a company's material in the
#   operator's own shelf          hodd/life/{work,marketing,meetings} -> the company's shelf
#   a layout map naming a
#   DIFFERENT MACHINE             .ymir-layout.yaml -> regenerated for this machine
#
# THE LAW: the home is the vault (Rule 04) and a private git repo, so:
#   * nothing is deleted — a file is MOVED, and the destination is recorded;
#   * nothing is clobbered — a name already present at the destination is left alone
#     and reported;
#   * every branch is guarded by existence, so a home that never saw these paths
#     pays nothing and this is a no-op on a fresh install.
#
# Idempotent: safe to run repeatedly.
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

# WHICH MACHINE IS THIS? The home and its strays differ by platform (Rule 05: one core,
# per-platform layers). Android/Termux says "Linux" but has no Documents/ and no USER;
# its home is short (~/ymir-home) and its strays are different ones.
PLATFORM="unknown"
if [ -r "$ROOT/bin/fleet/ymir-platform.sh" ]; then
  # shellcheck source=bin/fleet/ymir-platform.sh
  . "$ROOT/bin/fleet/ymir-platform.sh" 2>/dev/null || true
  command -v ymir_os >/dev/null 2>&1 && PLATFORM="$(ymir_os)"
fi

# The operator's home, through the ONE resolver (Rule 07) — never guessed, never env-only.
# shellcheck source=bin/vault/hoard-lib.sh
. "$ROOT/bin/vault/hoard-lib.sh" 2>/dev/null || true
HOME_DIR=""
command -v ymir_home_root >/dev/null 2>&1 && ymir_home_root HOME_DIR
[ -n "$HOME_DIR" ] || HOME_DIR="${YMIR_HOME:-}"
[ -n "$HOME_DIR" ] || { printf '0008: no home resolved — nothing touched\n'; exit 0; }
[ -f "$HOME_DIR/hodd/memory/runes_audit.md" ] || {
  printf '0008: %s is not a Ymir home (no hodd/memory/runes_audit.md) — nothing touched\n' "$HOME_DIR"
  exit 0
}

say() { printf '0008-home-layout: %s\n' "$*"; }
MOVED=0; LEFT=0

# move_path <from> <to>  — a move, never a delete; never clobbers; records the result.
move_path() {
  local from="$1" to="$2"
  [ -e "$from" ] || return 0
  if [ -e "$to" ]; then
    # the destination is taken: keep both, and say so — never overwrite a home's material
    local alt="$to.merged-$(date -u +%Y%m%d)"
    say "  kept  $from  (→ $alt: $to already exists)"
    mkdir -p "$(dirname "$alt")" && mv "$from" "$alt" 2>/dev/null || return 1
  else
    mkdir -p "$(dirname "$to")" && mv "$from" "$to" 2>/dev/null || return 1
    say "  move  $from  →  $to"
  fi
  MOVED=$((MOVED + 1))
}

# merge_dir <from> <to>  — fold a directory's contents in, one entry at a time, no clobber.
merge_dir() {
  local from="$1" to="$2" e
  [ -d "$from" ] || return 0
  mkdir -p "$to"
  for e in "$from"/* "$from"/.[!.]*; do
    [ -e "$e" ] || continue
    move_path "$e" "$to/$(basename "$e")"
  done
  rmdir "$from" 2>/dev/null || true
}

cd "$HOME_DIR" || exit 0
say "home: $HOME_DIR  (platform: $PLATFORM)"

# ── 1. the layout map must describe THIS machine ──────────────────────────────
LAY="$HOME_DIR/.ymir-layout.yaml"
if [ -f "$LAY" ]; then
  maproot="$(sed -nE 's/^git_repo: "([^"]+)".*/\1/p' "$LAY" | head -1)"
  if [ -n "$maproot" ] && [ "$maproot" != "$HOME_DIR" ]; then
    say "  the layout map names '$maproot' — regenerating it for this machine"
    {
      echo "version: 1"
      echo "# REGENERATED by 0008-home-layout: a map must describe THIS machine (Rule 21)."
      echo "layout:"
      for k in config secrets identity memory smidja state data svartalfaheim; do
        case "$k" in
          config|smidja|state|svartalfaheim) echo "  $k: \"$HOME_DIR/$k\"" ;;
          *) echo "  $k: \"$HOME_DIR/hodd/$k\"" ;;
        esac
      done
      echo "git_repo: \"$HOME_DIR\""
    } > "$LAY"
    MOVED=$((MOVED + 1))
  fi
fi

# ── 2. state belongs in the home, nowhere else (Rule 21) ──────────────────────
STAMP="$(date -u +%Y%m%d)"
if [ "$PLATFORM" = android ]; then
  # On a phone there is no Documents/ — but a home installed with the DESKTOP shape can
  # still be sitting there (the CLI resolves the home per machine: env → recorded →
  # ymirhome). If it is, fold it in; the desktop strays below cannot exist and are skipped.
  for stale in "$HOME/Documents/ymirhome" "$HOME/ymirhome"; do
    if [ -d "$stale" ] && [ "$stale" != "$HOME_DIR" ]; then
      say "  a desktop-shaped home at $stale — folding it in (the phone's home is $HOME_DIR)"
      merge_dir "$stale" "$HOME_DIR/state/from-desktop-home-$STAMP"
      LEFT=$((LEFT + 1))
    fi
  done
else
  for stray in "$HOME_DIR/../Ymir/state" "$HOME_DIR/../ymirhome.bak-scaffold/state"; do
    [ -d "$stray" ] && move_path "$stray" "$HOME_DIR/state/from-$(basename "$(dirname "$stray")")-$STAMP"
  done
fi
[ -d "$HOME_DIR/hodd/hodd" ] && move_path "$HOME_DIR/hodd/hodd" "$HOME_DIR/state/stray-hodd-hodd-$STAMP"
# a stray hoard beside the home: its content is the operator's — fold it in, never drop it
if [ -d "$HOME/hodd" ] && [ "$HOME/hodd" != "$HOME_DIR/hodd" ]; then
  say "  a stray hoard at $HOME/hodd — folding it into the real one"
  merge_dir "$HOME/hodd" "$HOME_DIR/hodd/from-stray-hodd-$STAMP"
fi
# state inside the repo tree (a git tree is not a runtime)
for d in "$ROOT/.agents/state" "$ROOT/bin/state"; do
  [ -d "$d" ] && merge_dir "$d" "$HOME_DIR/state/from-repo-$(basename "$(dirname "$d")")-$(basename "$d")-$STAMP"
done

# ── 3. companies live in the realms, not under identity ──────────────────────
if [ -d "$HOME_DIR/hodd/identity/companies" ]; then
  say "  companies under hodd/identity/ — moving each into svartalfaheim/"
  for c in "$HOME_DIR/hodd/identity/companies"/*/; do
    [ -d "$c" ] || continue
    name="$(basename "$c")"
    merge_dir "${c%/}" "$HOME_DIR/svartalfaheim/$name"
  done
  # the templates and examples that sat beside them go to the realm root
  for f in "$HOME_DIR/hodd/identity/companies"/.*; do
    case "$(basename "$f")" in .|..) continue ;; esac
    [ -f "$f" ] && move_path "$f" "$HOME_DIR/svartalfaheim/$(basename "$f")"
  done
  rmdir "$HOME_DIR/hodd/identity/companies" 2>/dev/null || true
  say "  NOTE: if any of those was a PRODUCT of a company, re-file it under"
  say "        svartalfaheim/<company>/products/<product>/ — only a person can tell."
  LEFT=$((LEFT + 1))
fi

# ── 4. the operator's own shelf holds the operator's own material ────────────
for sub in work marketing meetings; do
  d="$HOME_DIR/hodd/life/$sub"
  [ -d "$d" ] || continue
  say "  hodd/life/$sub holds company material — holding it for routing, not in the operator's shelf"
  merge_dir "$d" "$HOME_DIR/svartalfaheim/.inbox/life-$sub-$STAMP"
  LEFT=$((LEFT + 1))
done

# ── 5. two realms differing only by a trailing 's' are one company, misspelt ──
if [ -d "$HOME_DIR/svartalfaheim" ]; then
  for r in "$HOME_DIR/svartalfaheim"/*/; do
    n="$(basename "$r")"
    case "$n" in .*) continue ;; esac
    [ -d "$HOME_DIR/svartalfaheim/${n}s" ] && {
      say "  NOTE: '${n}' and '${n}s' both exist — one company, two spellings. Settle it by hand."
      LEFT=$((LEFT + 1))
    }
  done
fi

printf '0008-home-layout: %s moved, %s left for a person\n' "$MOVED" "$LEFT"
say "  verify with: bin/agents/eir-doctor.sh check   (the hoard surface must read 'ok')"
exit 0
