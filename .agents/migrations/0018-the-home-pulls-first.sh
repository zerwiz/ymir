#!/usr/bin/env bash
# 0018-the-home-pulls-first — seat RULES/50 in a home: the merge rules that make the
# fleet's concurrent writes merge themselves, and Claude's Ymir doors.
#
# WHY (2026-11-10, heimdall). One pull of the home met 1,077 conflicts; the next, minutes
# later, met two more; and one plan number was taken three times in an hour. The cause was
# not carelessness but shape: every seat and every cron appends to the same records, and
# nothing told git that an append-only file merges by UNION, or that a generated mirror is
# simply regenerated. The other half of the shape was a seat that commits and does not push.
# RULES/50 is the law; bin/vault/home-sync.sh is the door; this migration is how an existing
# home gets both on install, on `/updateymir` and on `eir-doctor fix`.
#
# WHAT IT DOES — idempotent, three steps:
#   1. adds a MARKED block to $YMIR_HOME/.gitattributes (never edits a line outside it):
#      append-only records -> merge=union; the assistant mirror -> merge=ours (regenerated
#      by learn-home, so either side is right and the next run re-stamps it);
#   2. seats the `ours` merge driver in this clone (`home-sync.sh setup`);
#   3. seats Claude Code's Ymir doors (`mcp-config.sh claude`) where claude is installed.
#   It ships the .gitattributes change through home-sync (pull, commit, push) at once.
#
# WHAT IT DOES NOT DO: rewrite a record, resolve an old conflict, or touch hodd/secrets.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
HOME_DIR="${YMIR_HOME:-}"
[ -n "$HOME_DIR" ] || { . "$ROOT/bin/vault/hoard-lib.sh" 2>/dev/null && ymir_home_root HOME_DIR; }
say() { printf '0018: %s\n' "$1"; }
[ -d "${HOME_DIR:-/nonexistent}/.git" ] || { say "no home git repo resolved — skip (Rule 25)"; exit 0; }

BEGIN_MARK='# >>> ymir: RULES/50 merge rules (0018) >>>'
END_MARK='# <<< ymir: RULES/50 merge rules (0018) <<<'
attrs="$HOME_DIR/.gitattributes"
if grep -qF "$BEGIN_MARK" "$attrs" 2>/dev/null; then
  say ".gitattributes block present"
else
  cat >>"$attrs" <<EOF

$BEGIN_MARK
# Append-only records (Rule 06) merge by UNION: both seats' new lines are kept, none lost.
hodd/memory/runes_audit.md merge=union
hodd/memory/**/*.jsonl merge=union
hodd/saves/**/*.jsonl merge=union
hodd/state/**/*.jsonl merge=union
svartalfaheim/**/*.jsonl merge=union
svartalfaheim/*/projects/*/plans/README.md merge=union
# Generated mirrors are regenerated by their own door (learn-home), so a conflict there is
# only a timestamp: keep this side, the next run re-stamps it. Needs merge.ours.driver=true.
hodd/identity/assistant/approved/** merge=ours
hodd/saves/assistant/*/identity/** merge=ours
$END_MARK
EOF
  say ".gitattributes block added"
fi

bash "$ROOT/bin/vault/home-sync.sh" setup >/dev/null 2>&1 && say "merge.ours.driver seated"

if ! git -C "$HOME_DIR" diff --quiet -- .gitattributes 2>/dev/null || ! git -C "$HOME_DIR" ls-files --error-unmatch .gitattributes >/dev/null 2>&1; then
  bash "$ROOT/bin/vault/home-sync.sh" ship "hoard: the merge rules of RULES/50 (migration 0018)" .gitattributes \
    && say ".gitattributes shipped" || say ".gitattributes written but NOT shipped — run bin/vault/home-sync.sh ship"
fi

if [ -x "$ROOT/bin/bridge/mcp-config.sh" ]; then
  bash "$ROOT/bin/bridge/mcp-config.sh" claude | sed 's/^/0018: /'
fi
exit 0
