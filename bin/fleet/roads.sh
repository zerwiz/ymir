#!/usr/bin/env bash
# Fleet roads — OUTPUT of the registry (hodd/data/fleet.json). Never hand-edited.
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# The home is RESOLVED, never guessed (Rule 07): the one resolver answers, and a seat that
# cannot answer is told so instead of silently reading a path this machine may not have.
# shellcheck disable=SC1091
. "$ROOT/bin/vault/hoard-lib.sh" 2>/dev/null || true
[ -n "${YMIR_HOME:-}" ] || ymir_home_root YMIR_HOME 2>/dev/null || true
if [ -z "${YMIR_HOME:-}" ]; then
  printf 'error: the home is unresolved — set YMIR_HOME, or run from a checkout\n' >&2
  printf 'help: bin/vault/hoard-lib.sh must be able to answer\n' >&2
  exit 2
fi
REG="$YMIR_HOME/hodd/data/fleet.json"

python3 - "$REG" "$@" <<'PY'
import json, sys, subprocess, os
reg=sys.argv[1]
args=sys.argv[2:]
cmd=args[0] if args else "docs"
d=json.load(open(reg))
hosts=d.get("hosts",{})

def road_hosts():
    out=[]
    for name,h in hosts.items():
        if h.get("tailnet") and h.get("user"):
            out.append((name,h))
    return out

MARKER_BEGIN="# >>> fleet-roads BEGIN (generated by bin/fleet/roads.sh) >>>"
MARKER_END="# <<< fleet-roads END <<<"

if cmd=="docs":
    for name,h in road_hosts():
        print(f"Host {name}")
        print(f"  HostName {h['tailnet']}")
        print(f"  User {h['user']}")
        print("  IdentityFile ~/.ssh/id_ed25519")
        print("  IdentitiesOnly yes")
        print()

elif cmd=="check":
    heart=d.get("heart")
    for name,h in road_hosts():
        if name==heart:
            hn=subprocess.run(["hostname"],capture_output=True,text=True).stdout.strip()
            print(f"{name}: up (local) {hn}")
            continue
        addr=h["tailnet"]; user=h["user"]
        try:
            r=subprocess.run(["ssh","-o","StrictHostKeyChecking=no","-o","ConnectTimeout=5","-o","BatchMode=yes",
                              f"{user}@{addr}","hostname"],capture_output=True,text=True,timeout=10)
            out=r.stdout.strip()
            if r.returncode==0 and out:
                print(f"{name}: up (tailnet) {out}")
            else:
                print(f"{name}: DARK")
        except Exception:
            print(f"{name}: DARK")

elif cmd=="status":
    # per role
    roles={}
    for name,h in hosts.items():
        for r in h.get("roles",[]):
            roles.setdefault(r,[]).append(name)
    for role in ["heart","forge","dev","hand"]:
        for name in roles.get(role,[]):
            h=hosts.get(name,{})
            if not h.get("tailnet") or not h.get("user"):
                print(f"{role} {name}: no road")
                continue
            if name==d.get("heart"):
                hn=subprocess.run(["hostname"],capture_output=True,text=True).stdout.strip()
                print(f"{role} {name}: up (local) {hn}")
            else:
                addr=h["tailnet"]; user=h["user"]
                try:
                    r=subprocess.run(["ssh","-o","StrictHostKeyChecking=no","-o","ConnectTimeout=5","-o","BatchMode=yes",
                                      f"{user}@{addr}","hostname"],capture_output=True,text=True,timeout=10)
                    out=r.stdout.strip()
                    if r.returncode==0 and out:
                        print(f"{role} {name}: up (tailnet) {out}")
                    else:
                        print(f"{role} {name}: DARK")
                except Exception:
                    print(f"{role} {name}: DARK")

elif cmd=="install":
    block=[]
    block.append(MARKER_BEGIN)
    for name,h in road_hosts():
        block.append(f"Host {name}")
        block.append(f"  HostName {h['tailnet']}")
        block.append(f"  User {h['user']}")
        block.append("  IdentityFile ~/.ssh/id_ed25519")
        block.append("  IdentitiesOnly yes")
    block.append(MARKER_END)
    block_text="\n".join(block)+"\n"
    cfg=os.path.expanduser("~/.ssh/config")
    if os.path.exists(cfg):
        lines=open(cfg).read().splitlines(keepends=True)
    else:
        lines=[]
    # remove existing marked block
    out=[]
    i=0
    inblock=False
    for line in lines:
        if line.strip()==MARKER_BEGIN:
            inblock=True
            continue
        if line.strip()==MARKER_END:
            inblock=False
            continue
        if not inblock:
            out.append(line)
    # ensure trailing newline
    text="".join(out)
    if text and not text.endswith("\n"):
        text+="\n"
    text+=block_text
    open(cfg,"w").write(text)
    print("installed")
else:
    print("unknown subcommand",cmd,file=sys.stderr); sys.exit(2)
PY
