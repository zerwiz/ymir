#!/usr/bin/env bash
# kit-history.sh — write kit-history.tsv: every file the kit has ever shipped, by path and git blob id.
#
# standardise.sh reads it to tell an unchanged file from an older kit (safe to upgrade) from a file a repository
# changed for itself (a local rule: reported, never replaced). Regenerate it in the release that changes the kit:
#
#   bash bin/collab/kit-history.sh            # rewrites bin/collab/kit-history.tsv from this repository's history
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(git -C "$here" rev-parse --show-toplevel)"
out="$here/kit-history.tsv"
{
  printf '# path\tblob — every version of every file bin/collab/kit has shipped (generated by kit-history.sh)\n'
  git -C "$root" rev-list HEAD -- bin/collab/kit | while read -r c; do
    git -C "$root" ls-tree -r "$c" -- bin/collab/kit | awk -F'\t' '{split($1,a," "); sub("^bin/collab/kit/","",$2); print $2 "\t" a[3]}'
  done | sort -u
} > "$out"
printf 'kit-history: %s entries\n' "$(($(wc -l < "$out") - 1))"
