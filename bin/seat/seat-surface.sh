#!/usr/bin/env bash
# seat-surface.sh — render THIS seat's own name into the AGENTS.md every harness reads.
#
#   bin/seat/seat-surface.sh            render the seat file and point every harness at it
#   bin/seat/seat-surface.sh --check    exit 1 when a surface is not the seat's own
#
# WHY (the Allfather, 2026-11-03): *"every machine and user needs to have their own
# names for that agent … it comes a lot of conflicts when several of Brokk exists.
# That needs to be a ymir home config that gets into all tools' AGENTS.md globally
# in installs and updates if they are still named Brokk."*
#
# The shared contract (the repo's AGENTS.md) names the counsellor's craft — Brokk.
# A seat whose primary is a different figure (Sindri on the smith's seat, Kvasir on
# compute, Forseti on the ledger) must NOT answer to that name. So the seat's name is
# a HOME CONFIG (`$YMIR_HOME/hodd/identity/seats.yaml`, read by seat-identity.sh) and
# this door renders it ABOVE the shared contract into one file —
# `~/.pi/agent/AGENTS.seat.md` — then points every harness instruction file at it.
#
# It NEVER writes the public repo. The repo contract stays shared; only the machine's
# copy carries the seat's name. Idempotent: safe in install and in every update.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SID="$ROOT/bin/agents/seat-identity.sh"
HOST="${YMIR_HOST:-$(hostname -s)}"
SEAT="$HOME/.pi/agent/AGENTS.seat.md"
if [ -z "${YMIR_HOME:-}" ]; then
  _hoard="$(bash "$ROOT/bin/vault/hodd.sh" path 2>/dev/null || true)"
  [ -n "$_hoard" ] || { printf 'seat-surface: no home — bin/vault/hodd.sh path answered nothing\n' >&2; exit 1; }
  YMIR_HOME="$(dirname "$_hoard")"
fi
export YMIR_HOME

# every file a harness instruction loader reads, where the harness is present
# (Pi · Claude Code · Codex · Cursor · Gemini CLI) — Rule 02: symlinks, never copies.
surfaces() {
  printf '%s\n' \
    "$HOME/.pi/agent/AGENTS.md" \
    "$HOME/.claude/CLAUDE.md" \
    "$HOME/.codex/AGENTS.md" \
    "$HOME/.cursorrules" \
    "$HOME/.gemini/GEMINI.md" \
    "$HOME/.hermes/AGENTS.md"
}

# Hermes reads .hermes.md from the git root up, and AGENTS.md from the root down.
# The seat's own name therefore rides a MACHINE-LOCAL .hermes.md at the repo root
# (gitignored — the public repo stays nameless, Rule 04), beside the shared contract.
render_hermes_md() {
  local out="$ROOT/.hermes.md" name role
  name="$(bash "$SID" "$HOST" 2>/dev/null || true)"
  [ -n "$name" ] || { printf 'seat-surface: no seat identity - .hermes.md not written\n' >&2; return 1; }
  role="$(sed -n 's/^role=//p' "$HOME/.pi/agent/extensions/.ymir-seat" 2>/dev/null)"
  {
    printf '<!-- generated by bin/seat/seat-surface.sh - do not edit; machine-local (gitignored) -->\n'
    printf '# This seat: %s\n\n' "$HOST"
    printf 'You are **%s** on **%s** - %s. Read `AGENTS.md` in this repository as the house craft and voice.\n' "$name" "$HOST" "${role:-the seat primary}"
    printf 'That contract is written in the counsellor voice and names **Brokk** - that is the counsellor craft, not your name. You answer as **%s**.\n\n' "$name"
    printf 'The operator of this fleet is %s. Address him by that name: in a federated hall a bare "Allfather" names nobody.\n' "${OPERATOR:-<the operator, unnamed in the config>}"
    printf 'English for the work, Old Norse for the names; nothing else inside Ymir (Rule 43).\n'
  } > "$out"
  printf 'seat-surface: %s written (Hermes reads it first)\n' "$out"
}

# SOUL.md is Hermes' PRIMARY IDENTITY (slot #1 of the system prompt), read from
# ~/.hermes/SOUL.md - never the working directory. It is where the house voice and the
# seat's own name belong if they must follow the agent everywhere.
render_hermes_soul() {
  local soul="$HOME/.hermes/SOUL.md" name role tpl
  [ -d "$HOME/.hermes" ] || return 0
  tpl="$ROOT/bin/seat/assets/hermes-soul.md.in"
  [ -r "$tpl" ] || { printf 'seat-surface: no SOUL template at %s\n' "$tpl" >&2; return 1; }
  name="$(bash "$SID" "$HOST" 2>/dev/null || true)"
  [ -n "$name" ] || return 0
  case "$(printf '%s' "$name" | tr '[:upper:]' '[:lower:]')" in
    brokk) printf 'seat-surface: the roster names this seat primary "brokk" — Brokk is the counsellor ROLE, never an agent name; name this machine its own (RULES/25, the Allfather 2026-11-03)\n' >&2; return 1 ;;
  esac
  role="$(sed -n 's/^role=//p' "$HOME/.pi/agent/extensions/.ymir-seat" 2>/dev/null)"
  block="$(python3 - "$tpl" "$YMIR_HOME" "$HOST" "$name" "$role" "$ROOT" "${OPERATOR:-}" <<'PY2'
import os, sys
tpl, home, host, seat, role, root, operator = sys.argv[1:8]
import yaml
cfg = yaml.safe_load(open(os.path.join(home, 'hodd', 'identity', 'seats.yaml'))) or {}
seat_cfg = (cfg.get('seats') or {}).get(host) or {}
ma = seat_cfg.get('machine_agent') or {}
mname = (ma.get('name') or '').strip()
mrole = (ma.get('role') or "the machine's counsellor").strip()
if mname:
    machine = mname
else:
    machine = "unnamed (the roster has not sealed a machine-agent name for this host — ask the Allfather for it)"
text = open(tpl).read()
for k, v in {
    '__HOST__': host, '__MACHINE_AGENT__': machine, '__MACHINE_ROLE__': mrole,
    '__SEAT_NAME__': seat, '__OPERATOR__': operator or '<the operator, unnamed in the config>',
    '__ROOT__': root, '__YMIR_HOME__': home,
    '__FLEET__': ((cfg.get('fleet') or {}).get('name') or 'the Ymir fleet'),
    '__HOUSE__': ((cfg.get('fleet') or {}).get('house') or 'the operator''s house'),
}.items():
    text = text.replace(k, v)
print(text, end='')
PY2
)"
  if [ ! -f "$soul" ]; then
    printf '%s\n' "$block" > "$soul"
  elif grep -q 'ymir-seat:begin' "$soul" 2>/dev/null; then
    python3 - "$soul" "$block" <<'PY2'
import re, sys
p, block = sys.argv[1], sys.argv[2]
s = open(p).read()
s = re.sub(r'<!-- ymir-seat:begin.*?<!-- ymir-seat:end -->', block.rstrip('\n'), s, flags=re.S)
open(p, 'w').write(s)
PY2
  else
    printf '\n%s\n' "$block" >> "$soul"
  fi
  printf 'seat-surface: %s carries the house identity\n' "$soul"
}

render() {
  [ -x "$SID" ] || { printf 'seat-surface: no seat-identity.sh at %s\n' "$SID" >&2; return 2; }
  bash "$SID" --render "$HOST" >/dev/null 2>&1 || {
    printf 'seat-surface: the seat has no identity in the roster — run bin/agents/seat-identity.sh --ensure\n' >&2
    return 1
  }
  [ -r "$SEAT" ] || { printf 'seat-surface: %s was not rendered\n' "$SEAT" >&2; return 1; }
}

link() {
  local f
  while IFS= read -r f; do
    [ -e "$(dirname "$f")" ] || continue          # the harness is not on this machine
    if [ -L "$f" ] && [ "$(readlink -f "$f")" = "$(readlink -f "$SEAT")" ]; then continue; fi
    # a real file is never overwritten silently: it is moved aside once, by name
    if [ -e "$f" ] && [ ! -L "$f" ]; then
      mv "$f" "$f.pre-seat-surface-$(date +%Y%m%d)" || return 1
      printf 'seat-surface: set aside %s (a real file, kept)\n' "$f" >&2
    fi
    mkdir -p "$(dirname "$f")"
    ln -sfn "$SEAT" "$f" && printf 'seat-surface: %s -> %s\n' "$f" "$(basename "$SEAT")"
  done < <(surfaces)
}

case "${1:-}" in
  -h|--help) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//;s/^$//' | head -14; exit 0 ;;
  --check)
    render || exit 1
    NAME="$(bash "$SID" "$HOST" 2>/dev/null)"
    bad=0
    head1="$(sed -n '4p' "$SEAT" 2>/dev/null)"
    case "$head1" in *"$NAME"*) printf 'seat-surface: seat file names %s ✓\n' "$NAME" ;; *) printf 'seat-surface: seat file does not name %s\n' "$NAME"; bad=1 ;; esac
    OPERATOR="$(python3 -c "import yaml;d=yaml.safe_load(open('$YMIR_HOME/hodd/identity/operator.yaml'));print((d.get('allfather') or {}).get('display') or 'Allfather')" 2>/dev/null || echo Allfather)"
    if [ -n "$OPERATOR" ] && grep -qF "$OPERATOR" "$SEAT" 2>/dev/null; then
      printf 'seat-surface: seat file names the operator (%s) ✓\n' "$OPERATOR"
    else
      printf 'seat-surface: the operator is not named in the seat file (%s)\n' "${OPERATOR:-<empty>}"; bad=1
    fi
    while IFS= read -r f; do
      [ -e "$(dirname "$f")" ] || continue
      [ -L "$f" ] && [ "$(readlink -f "$f")" = "$(readlink -f "$SEAT")" ] && continue
      printf 'seat-surface: %s does not resolve to the seat file\n' "$f"; bad=1
    done < <(surfaces)
    if [ -f "$HOME/.hermes/SOUL.md" ]; then
      grep -q 'ymir-seat:begin' "$HOME/.hermes/SOUL.md" 2>/dev/null && printf 'seat-surface: SOUL.md carries the house identity ✓\n' || { printf 'seat-surface: SOUL.md lacks the ymir-seat block\n'; bad=1; }
    fi
    [ -f "$ROOT/.hermes.md" ] && printf 'seat-surface: .hermes.md is written ✓\n' || { printf 'seat-surface: .hermes.md is missing (Hermes reads it first)\n'; bad=1; }
    [ "$bad" -eq 0 ] && printf 'seat-surface: every harness reads %s on %s\n' "$NAME" "$HOST"
    exit "$bad" ;;
  ""|--apply|apply)
    render || exit 1
    OPERATOR="$(python3 -c "import yaml;d=yaml.safe_load(open('$YMIR_HOME/hodd/identity/operator.yaml'));print((d.get('allfather') or {}).get('display') or '')" 2>/dev/null || true)"
  [ -n "$OPERATOR" ] || { printf 'seat-surface: the operator is not named in hodd/identity/operator.yaml — the seat file names none (never an invented one)\n' >&2; OPERATOR='<the operator, unnamed in the config>'; }
    render_hermes_md || true
    render_hermes_soul || true
    link || exit 1
    printf 'seat-surface: %s on %s — %s\n' "$(bash "$SID" "$HOST" 2>/dev/null)" "$HOST" "$(basename "$SEAT")" ;;
  *) printf 'error: unknown action %s\nhelp: seat-surface.sh [--check]\n' "$1" >&2; exit 2 ;;
esac
