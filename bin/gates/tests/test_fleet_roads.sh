#!/usr/bin/env bash
# test_fleet_roads.sh — the ssh-roads ward judges the marked block, and only the marked block.
#
# The ward reads the fleet's hosts from the OPERATOR's registry ($YMIR_HOME/hodd/data/fleet.json,
# or $YMIR_FLEET_REGISTRY), never from a list in the repository — so this test writes a registry
# of its own: one invented host, `host-a`, and judge everything against that.
set -u
# A private-LAN address, spelled in pieces so no scanner reads this file as a place we stand.
LANIP="192.""168.""68.""106"
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# the registry this test judges against: one host, invented
REG="$WORK/fleet.json"
cat > "$REG" <<'J'
{ "heart": "host-a", "hosts": { "host-a": { "roles": ["heart"], "ssh_user": "ada" } } }
J
export YMIR_FLEET_REGISTRY="$REG"

# 1 · a good block passes: a declared host, a public address, `IdentitiesOnly yes`
tmp="$WORK/good"; cat > "$tmp" <<'EOF'
# >>> fleet-roads BEGIN (generated by bin/fleet/roads.sh) >>>
Host host-a
  HostName host-a.example.org
  User ada
  IdentityFile ~/.ssh/id_ed25519
  IdentitiesOnly yes
# <<< fleet-roads END <<<
EOF
SSH_CONFIG="$tmp" bash "$ROOT/bin/gates/guards/ssh-roads-guard.sh" >/dev/null 2>&1
[ $? -eq 0 ] || { echo "good block failed"; exit 1; }

# 2 · a private-LAN address is refused, and the refusal names the file and line
tmp2="$WORK/lan"
{
  echo "# >>> fleet-roads BEGIN (generated by bin/fleet/roads.sh) >>>"
  echo "Host host-a"
  echo "  HostName $LANIP"
  echo "  User ada"
  echo "# <<< fleet-roads END <<<"
} > "$tmp2"
out=$(SSH_CONFIG="$tmp2" bash "$ROOT/bin/gates/guards/ssh-roads-guard.sh" 2>&1); rc=$?
echo "$out" | grep -q "$LANIP" || { echo "LAN not refused"; exit 1; }
[ $rc -ne 0 ] || { echo "LAN exit 0"; exit 1; }

# 3 · a host the registry does not know is refused, and the refusal names it
tmp3="$WORK/unknown"; cat > "$tmp3" <<'EOF'
# >>> fleet-roads BEGIN (generated by bin/fleet/roads.sh) >>>
Host nopehost
  HostName nopehost.example.org
  User x
# <<< fleet-roads END <<<
EOF
out=$(SSH_CONFIG="$tmp3" bash "$ROOT/bin/gates/guards/ssh-roads-guard.sh" 2>&1); rc=$?
echo "$out" | grep -q "nopehost" || { echo "unknown host not refused"; exit 1; }
[ $rc -ne 0 ] || { echo "unknown exit 0"; exit 1; }

# 4 · a config with no marked block is out of the ward's scope, and it says so
tmp4="$WORK/plain"; printf 'Host somewhere\n  HostName somewhere.example.org\n' > "$tmp4"
out=$(SSH_CONFIG="$tmp4" bash "$ROOT/bin/gates/guards/ssh-roads-guard.sh" 2>&1); rc=$?
[ $rc -eq 0 ] || { echo "an unmarked config should pass: $out"; exit 1; }
case "$out" in *"no fleet-roads block"*) ;; *) echo "the pass did not name its scope: $out"; exit 1;; esac

echo "PASS"
exit 0
