#!/usr/bin/env bash
# queue.sh — THE work queue, and it is DERIVED, never authored.
#
# WHY (2026-10-02): the to-do has lived in three wrong places — an in-session list
# that vanishes, and twice inside a document that should not have held it (the
# register, twice, by this same hand). A queue that is *authored* rots and
# duplicates; so this one is a VIEW over the two documents that already hold the
# truth, and the only place anyone writes anything is those two.
#
#   bin/gates/queue.sh            regenerate plans/queue.md from register.md + questions.md
#   bin/gates/queue.sh --check    fail when queue.md is stale (wire this into CI)
#
# SOURCES (the only places a row is ever added):
#   register.md    §1 the asks        — state: done | blocked | owed | open
#   questions.md   the questions      — kind: BLOCKING | SEALED | OWED
set -uo pipefail

_root() {
  local d; d="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  while [ "$d" != "/" ]; do
    [ -d "$d/.pi" ] && [ -d "$d/RULES" ] && { printf '%s' "$d"; return 0; }
    d="$(dirname "$d")"
  done
  printf '%s' "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
}
ROOT="$(_root)"
MODE="${1:-write}"
# The plan shelf is the HOME's, resolved by the one resolver — never a literal
# $HOME/... path (defaults-guard refused exactly that on this file's first draft).
PLAN_DIR="${YMIR_PLAN_DIR:-}"
if [ -z "$PLAN_DIR" ]; then
  _h="${YMIR_HOME:-}"
  if [ -z "$_h" ] && [ -r "$ROOT/bin/vault/hoard-lib.sh" ]; then
    . "$ROOT/bin/vault/hoard-lib.sh" 2>/dev/null || true
    command -v ymir_home_root >/dev/null 2>&1 && ymir_home_root _h
  fi
  # Last resort is hodd.sh's own resolver — never a literal path written here
  # (the ward refuses the literal, and rightly: it is this machine's layout).
  [ -n "$_h" ] || _h="$(bash "$ROOT/bin/vault/hodd.sh" path 2>/dev/null || true)"
  PLAN_DIR="$_h/svartalfaheim/whynotproductions/projects/ymir/plans"
fi
REG="$PLAN_DIR/register.md"
Q="$PLAN_DIR/questions.md"
OUT="$PLAN_DIR/queue.md"

# The register and the questions live in the operator's PRIVATE vault — which is deliberately
# NOT in this repository. So on CI (or any checkout without a vault) this gate cannot run, and
# it must SAY SO rather than report a verdict. That is the third instance of one lesson today:
# a thing that cannot start must say so in its own words, because a gate that fails for a
# missing input reads as "this repository is broken". Verdict: SKIP, exit 0.
[ -f "$REG" ] || {
  if [ "$MODE" = "--check" ]; then
    printf 'queue[1]{verdict,why}: "SKIP","the plan register is not in this repository — it lives in the operator vault (%s), and CI has none. Nothing is stale; nothing was checked."\n' "$REG"
    exit 0
  fi
  echo "queue: no register at $REG" >&2; exit 1
}
[ -f "$Q" ] || {
  if [ "$MODE" = "--check" ]; then
    printf 'queue[1]{verdict,why}: "SKIP","no questions file in the vault (%s). Nothing is stale; nothing was checked."\n' "$Q"
    exit 0
  fi
  echo "queue: no questions at $Q" >&2; exit 1
}

python3 - "$REG" "$Q" <<'PY'
import re, sys, datetime
reg, q = sys.argv[1], sys.argv[2]
rows = []

def cells(line):
    return [c.strip() for c in line.strip().strip('|').split('|')]

# register §1 — the asks: | area | ask | state | plan/where |
for ln in open(reg):
    if not ln.startswith('|'): continue
    c = cells(ln)
    if len(c) < 4: continue
    state = c[2].strip('* ').lower()
    if state not in ('done', 'blocked', 'owed', 'open'): continue
    rows.append(dict(kind='ask', state=state, what=c[1], where=c[3],
                     blocks=c[0], unblocks=''))

# questions.md — | # | question | kind | unblocks |
for ln in open(q):
    if not ln.startswith('|'): continue
    c = cells(ln)
    if len(c) < 4: continue
    kind = c[2].strip('* ').upper()
    if kind not in ('BLOCKING', 'SEALED', 'OWED'): continue
    state = 'blocked' if kind == 'BLOCKING' else ('owed' if kind == 'OWED' else 'open')
    rows.append(dict(kind='question', state=state, what=c[1], where='questions.md',
                     blocks=c[0], unblocks=c[3]))

ORDER = {'blocked': 0, 'owed': 1, 'open': 2, 'done': 3}
LABEL = {'blocked': 'BLOCKED — waiting on the Allfather', 'owed': 'OWED — my debt, no decision needed',
         'open': 'OPEN — ready to start', 'done': 'DONE — closed, kept for the record'}
today = datetime.date.today().isoformat()

out = [f"# The work queue — derived, {today}\n",
       "**GENERATED by `bin/gates/queue.sh` from [`register.md`](register.md) §1 and",
       "[`questions.md`](questions.md). Do not edit this file: edit a source, then regenerate.**",
       "`bin/gates/queue.sh --check` fails when this view is stale, so it cannot drift.\n",
       "```",
       "a queue that is AUTHORED rots and duplicates — which is how the register became a",
       "to-do list twice. This one is a VIEW, so the two documents above remain the only",
       "places anything is written.\n",
       "```\n"]
for st in ('blocked', 'owed', 'open', 'done'):
    sel = [r for r in rows if r['state'] == st]
    if not sel: continue
    sel.sort(key=lambda r: ORDER[st])
    out.append(f"## {LABEL[st]} — {len(sel)}\n")
    out.append("| # | what | where the thinking lives | unblocks |")
    out.append("|---|---|---|---|")
    for r in sel:
        what = r['what'].replace('|', '/')[:110]
        where = r['where'].replace('|', '/')[:60]
        unl = (r['unblocks'] or '').replace('|', '/')[:70]
        out.append(f"| {r['blocks']} | {what} | {where} | {unl} |")
    out.append("")
n = {k: sum(1 for r in rows if r['state'] == k) for k in ('blocked', 'owed', 'open', 'done')}
out.append(f"**Tally.** blocked={n['blocked']} owed={n['owed']} open={n['open']} done={n['done']}\n")
open(sys.argv[2] if False else '/dev/stdout', 'w').write("\n".join(out))
PY
rc=$?

render() {
OUT_T="$(mktemp)"
python3 - "$REG" "$Q" > "$OUT_T" <<'PY'
import sys, io, contextlib
buf = io.StringIO()
with contextlib.redirect_stdout(buf):
    exec(open('/dev/stdin').read()) if False else None
PY
# regenerate deterministically into the file (the heredoc above printed to stdout; do it once cleanly)
python3 - "$REG" "$Q" > "$OUT_T" <<'PY'
import sys, datetime
reg, q = sys.argv[1], sys.argv[2]
rows=[]
def cells(l): return [c.strip() for c in l.strip().strip('|').split('|')]
for ln in open(reg):
    if not ln.startswith('|'): continue
    c=cells(ln)
    if len(c)<4: continue
    st=c[2].strip('* ').lower()
    if st in ('done','blocked','owed','open'): rows.append((st,c[0],c[1],c[3],''))
for ln in open(q):
    if not ln.startswith('|'): continue
    c=cells(ln)
    if len(c)<4: continue
    k=c[2].strip('* ').upper()
    if k in ('BLOCKING','SEALED','OWED'):
        rows.append(('blocked' if k=='BLOCKING' else ('owed' if k=='OWED' else 'open'), c[0], c[1], 'questions.md', c[3]))
L={'blocked':'BLOCKED — waiting on the Allfather','owed':'OWED — my debt, no decision needed',
   'open':'OPEN — ready to start','done':'DONE — closed, kept for the record'}
d=datetime.date.today().isoformat()
print(f"# The work queue — derived, {d}\n")
print("**GENERATED by `bin/gates/queue.sh` from [`register.md`](register.md) §1 and")
print("[`questions.md`](questions.md). Do not edit this file: edit a source, then regenerate.**")
print("`bin/gates/queue.sh --check` fails when this view is stale, so it cannot drift.\n")
print("A queue that is AUTHORED rots and duplicates — which is how the register became a")
print("to-do list twice. This one is a VIEW, so the two documents above remain the only")
print("places anything is written.\n")
for st in ('blocked','owed','open','done'):
    sel=[r for r in rows if r[0]==st]
    if not sel: continue
    print(f"## {L[st]} — {len(sel)}\n")
    print("| # | what | where the thinking lives | unblocks |")
    print("|---|---|---|---|")
    for r in sel:
        print(f"| {r[1]} | {r[2].replace('|','/')[:110]} | {r[3].replace('|','/')[:60]} | {r[4].replace('|','/')[:70]} |")
    print()
n={k:sum(1 for r in rows if r[0]==k) for k in ('blocked','owed','open','done')}
print(f"**Tally.** blocked={n['blocked']} owed={n['owed']} open={n['open']} done={n['done']}")
PY
}

if [ "$MODE" != "--check" ]; then render; fi


if [ "$MODE" = "--check" ]; then
  render            # render to a TEMP; --check must never touch the queue it verifies
  if [ ! -f "$OUT" ] || ! diff -q "$OUT" "$OUT_T" >/dev/null 2>&1; then
    echo "queue --check: $OUT is STALE — run bin/gates/queue.sh" >&2; rm -f "$OUT_T"; exit 1
  fi
  echo "queue --check: current ($(grep -c '^| ' "$OUT") rows)"
  rm -f "$OUT_T"; exit 0
fi

render
cp "$OUT_T" "$OUT"; rm -f "$OUT_T"
echo "wrote $OUT"
grep -E '^\*\*Tally' "$OUT"
exit 0