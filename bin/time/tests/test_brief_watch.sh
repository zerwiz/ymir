#!/usr/bin/env bash
# test_brief_watch.sh — the morning brief is judged, not just run.
#
# The 07:00 row publishes the brief and then exits 1 when a draft has aged, so the
# scheduler says "job failed (rc=1)" over a document that exists and is complete. Four
# mornings then read the same way, and two of them read as nothing at all.
#
# What is proven here, and why each one is a hole worth a test:
#
#   Clean        a clean day is SILENT — the notify door is never called at all, and the
#                no-op is recorded, so a quiet morning leaves a mark that it was checked.
#   Aged         a draft that aged is ONE line naming how many, and saying plainly that
#                they are send-or-discard.
#   DoorMissing  a drafts door that never shipped is ONE line naming the stale pin —
#                the case where the brief exits 0 and says nothing today.
#   DidNotFire   a 07:00 row that never ran is ONE line naming the scheduler — the case
#                that today is indistinguishable from a clean morning.
#   OneLine      a not-clean day sends exactly one line and exits 0, because the
#                scheduler notifies on a non-zero row and a second line would say less.
#   OldShape     a brief with no drafts line at all (an older job wrote it) is NOT a clean
#                day — it is one line naming the stale pin.
#   Undeliverable a watchdog that cannot speak exits 1, so the scheduler's own notice
#                carries it — a watcher that cannot talk must not be silent.
#
# The notify door is stood in front of by a stub (BROKK_BRIEF_WATCH_NOTIFY), so "did it
# speak" is a file, not an opinion. Nothing here talks to Telegram.
#
# Usage: test_brief_watch.sh [Name …]
# Exit: 0 all pass · 1 a failure.
set -u
HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd -- "$HERE/../../.." && pwd)
DOOR="$ROOT/bin/time/nornir-job-brief-watch.sh"

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

pass=0; fail=0
ok()  { pass=$((pass + 1)); printf '  ok   %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf '  FAIL %s\n' "$1"; [ -n "${2:-}" ] && printf '       %s\n' "$2"; return 0; }

TODAY=2026-11-17
WATCHED="bin/time/nornir-job-daily-briefing.sh"
NOW_STAMP="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
OLD_STAMP="$(date -u -d '26 hours ago' +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u -v-26H +%Y-%m-%dT%H:%M:%SZ)"
STALE_STAMP="$(date -u -d '23 hours ago' +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u -v-23H +%Y-%m-%dT%H:%M:%SZ)"

# The stub in front of the notify door: it records the call, and its exit code is what
# the caller can set per case.
STUB="$TMP/notify"
cat >"$STUB" <<'STUBEOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$BRIEF_WATCH_TEST_NOTIFY_LOG"
exit "${BRIEF_WATCH_TEST_NOTIFY_RC:-0}"
STUBEOF
chmod +x "$STUB"

# ── the planted seat: a home, a state log, a brief, and the stub ──────────────────────
seat() {  # <case-name> — a fresh, empty seat under $TMP
  C="$TMP/$1"
  mkdir -p "$C/home/state" "$C/brief" "$C/state"
  : >"$C/notify.log"
  printf '%s\n' "$C"
}

run() {  # <case-dir> <notify-rc> [extra args…]
  local c="$1" nrc="$2"; shift 2
  YMIR_HOME="$c/home" \
  BROKK_CRON_LOG="$c/state/cron.log" \
  BROKK_BRIEF_DIR="$c/brief" \
  BROKK_BRIEF_WATCH_LAST="$c/state/brief-watch.last" \
  BROKK_BRIEF_WATCH_NOTIFY="$STUB" \
  BROKK_BRIEF_WATCH_TODAY="$TODAY" \
  BRIEF_WATCH_TEST_NOTIFY_LOG="$c/notify.log" \
  BRIEF_WATCH_TEST_NOTIFY_RC="$nrc" \
  bash "$DOOR" "$@" 2>"$c/stderr"
}

brief() {  # <case-dir> <drafts line or empty>
  local c="$1" line="${2-}"
  { printf '# Daily Briefing — %s\n\n' "$TODAY"
    printf 'Realm: `work` · Generated by Sága (Nornir 07:00, deterministic)\n\n'
    printf '### The letters nobody sent\n\n'
    [ -n "$line" ] && printf -- '- %s\n' "$line"
  } >"$c/brief/$TODAY.md"
}

wanted() {  # <name> — an optional filter from argv
  [ "$#" -eq 0 ] && return 0
  local w; for w in "$@"; do [ "$w" = "$CASE" ] && return 0; done
  return 1
}

printf 'brief-watch — the morning brief is judged, not just run\n'

# ── Clean: silence, and a no-op that proves it was checked ───────────────────────────
CASE=Clean
if wanted "$@"; then
  c=$(seat clean)
  printf '%s cron run: %s\nbriefing: wrote %s (1 bytes)\n' "$NOW_STAMP" "$WATCHED" "$c/brief/$TODAY.md" >"$c/state/cron.log"
  brief "$c" 'drafts: none — nothing is written and left unwritten'
  run "$c" 0 >/dev/null; rc=$?
  [ "$rc" = 0 ] && ok "$CASE exits 0" || bad "$CASE exits 0" "rc=$rc"
  [ -s "$c/notify.log" ] && bad "$CASE is silent" "$(cat "$c/notify.log")" || ok "$CASE never calls the notify door"
  grep -q '^.* clean — nothing said$' "$c/state/brief-watch.last" 2>/dev/null \
    && ok "$CASE records the no-op" || bad "$CASE records the no-op" "$(cat "$c/state/brief-watch.last" 2>/dev/null || echo '(no record)')"
fi

# ── Aged: one line, how many, and that they are send-or-discard ──────────────────────
CASE=Aged
if wanted "$@"; then
  c=$(seat aged)
  printf '%s cron run: %s\nbriefing: wrote x (1 bytes)\n' "$NOW_STAMP" "$WATCHED" >"$c/state/cron.log"
  printf '%s cron FAIL rc=1 %s :: the work was done, but not clean — drafts: 2 of 7 older than 2 days\n' \
    "$NOW_STAMP" "$WATCHED" >>"$c/state/cron.log"
  brief "$c" 'drafts: 2 of 7 older than 2 days — "spec v2.5" (3 days) · "reply to a correspondent" (2 days)'
  run "$c" 0 >/dev/null; rc=$?
  line=$(cat "$c/notify.log" 2>/dev/null)
  [ "$rc" = 0 ] && ok "$CASE exits 0 (the scheduler must not add a second line)" || bad "$CASE exits 0" "rc=$rc"
  [ "$(grep -c . "$c/notify.log" 2>/dev/null)" = 1 ] && ok "$CASE sends exactly one line" || bad "$CASE sends exactly one line" "$line"
  case "$line" in *"2 of 7"*"older than 2 days"*) ok "$CASE names how many drafts and how old" ;; *) bad "$CASE names how many drafts and how old" "$line" ;; esac
  case "$line" in *"send or discard"*) ok "$CASE says the drafts are send-or-discard" ;; *) bad "$CASE says the drafts are send-or-discard" "$line" ;; esac
  case "$line" in *"next: "*"draft-age.sh"*) ok "$CASE drafts the next act" ;; *) bad "$CASE drafts the next act" "$line" ;; esac
fi

# ── DoorMissing: the pin is stale, and the brief itself exited 0 ─────────────────────
CASE=DoorMissing
if wanted "$@"; then
  c=$(seat door)
  printf '%s cron run: %s\nbriefing: wrote x (1 bytes)\n' "$NOW_STAMP" "$WATCHED" >"$c/state/cron.log"
  brief "$c" 'drafts: SKIP — the door is missing (bin/mail/draft-age.sh)'
  run "$c" 0 >/dev/null; rc=$?
  line=$(cat "$c/notify.log" 2>/dev/null)
  [ "$rc" = 0 ] && ok "$CASE exits 0" || bad "$CASE exits 0" "rc=$rc"
  [ "$(grep -c . "$c/notify.log" 2>/dev/null)" = 1 ] && ok "$CASE sends exactly one line" || bad "$CASE sends exactly one line" "$line"
  case "$line" in *"pin is stale"*) ok "$CASE names the stale pin" ;; *) bad "$CASE names the stale pin" "$line" ;; esac
  case "$line" in *"pin-refresh"*) ok "$CASE names pin-refresh as the act" ;; *) bad "$CASE names pin-refresh as the act" "$line" ;; esac
fi

# ── DidNotFire: the row never ran, so there is no record at all ──────────────────────
CASE=DidNotFire
if wanted "$@"; then
  c=$(seat notfire)
  printf '%s cron run: %s\nbriefing: wrote yesterday (1 bytes)\n' "$OLD_STAMP" "$WATCHED" >"$c/state/cron.log"
  run "$c" 0 >/dev/null; rc=$?
  line=$(cat "$c/notify.log" 2>/dev/null)
  [ "$rc" = 0 ] && ok "$CASE exits 0" || bad "$CASE exits 0" "rc=$rc"
  [ "$(grep -c . "$c/notify.log" 2>/dev/null)" = 1 ] && ok "$CASE sends exactly one line" || bad "$CASE sends exactly one line" "$line"
  case "$line" in *"did not run"*) ok "$CASE says the row did not run" ;; *) bad "$CASE says the row did not run" "$line" ;; esac
  case "$line" in *"nornir-cron-start.sh --status"*) ok "$CASE names the scheduler as where to look" ;; *) bad "$CASE names the scheduler as where to look" "$line" ;; esac
fi

# ── OneLine: a stale fire inside the window still judges the file that is there ──────
CASE=OneLine
if wanted "$@"; then
  c=$(seat oneline)
  # The row fired 23h ago and wrote nothing for TODAY: the brief is missing, and that is
  # one line — never the "did not fire" line AND a "missing brief" line.
  printf '%s cron run: %s\n' "$STALE_STAMP" "$WATCHED" >"$c/state/cron.log"
  run "$c" 0 >/dev/null; rc=$?
  [ "$(grep -c . "$c/notify.log" 2>/dev/null)" = 1 ] && ok "$CASE is one message, not a stream" \
    || bad "$CASE is one message, not a stream" "$(cat "$c/notify.log" 2>/dev/null)"
  [ "$rc" = 0 ] && ok "$CASE exits 0" || bad "$CASE exits 0" "rc=$rc"
fi

# ── OldShape: a brief written before the drafts line existed is not a clean day ──────
CASE=OldShape
if wanted "$@"; then
  c=$(seat oldshape)
  printf '%s cron run: %s\n' "$NOW_STAMP" "$WATCHED" >"$c/state/cron.log"
  # measured 2026-11-17: every brief before that day carried no drafts line at all
  printf '# Daily Briefing — %s\n\n## 4. Today\x27s Runes\n\nNo Runes carved today yet.\n' "$TODAY" >"$c/brief/$TODAY.md"
  run "$c" 0 >/dev/null; rc=$?
  line=$(cat "$c/notify.log" 2>/dev/null)
  [ "$(grep -c . "$c/notify.log" 2>/dev/null)" = 1 ] && ok "$CASE sends exactly one line" || bad "$CASE sends exactly one line" "$line"
  case "$line" in *"no drafts line"*) ok "$CASE refuses to call it clean" ;; *) bad "$CASE refuses to call it clean" "$line" ;; esac
  case "$line" in *"pin is stale"*"pin-refresh"*) ok "$CASE names the stale pin as the act" ;; *) bad "$CASE names the stale pin as the act" "$line" ;; esac
  [ "$rc" = 0 ] && ok "$CASE exits 0" || bad "$CASE exits 0" "rc=$rc"
fi

# ── Undeliverable: a watchdog that cannot talk says so loudly ────────────────────────
CASE=Undeliverable
if wanted "$@"; then
  c=$(seat undeliverable)
  printf '%s cron run: %s\n' "$NOW_STAMP" "$WATCHED" >"$c/state/cron.log"
  printf '%s cron FAIL rc=1 %s :: the work was done, but not clean — drafts: 1 of 3 older than 2 days\n' \
    "$NOW_STAMP" "$WATCHED" >>"$c/state/cron.log"
  brief "$c" 'drafts: 1 of 3 older than 2 days — "spec v2.5" (3 days)'
  run "$c" 1 >/dev/null; rc=$?
  [ "$rc" = 1 ] && ok "$CASE exits 1 so the scheduler carries it" || bad "$CASE exits 1 so the scheduler carries it" "rc=$rc"
  grep -q 'COULD NOT DELIVER' "$c/state/brief-watch.last" 2>/dev/null \
    && ok "$CASE records that it could not deliver" || bad "$CASE records that it could not deliver" "$(cat "$c/state/brief-watch.last" 2>/dev/null || echo '(no record)')"
  grep -q 'could not deliver' "$c/stderr" 2>/dev/null && ok "$CASE says why on stderr" || bad "$CASE says why on stderr" "$(cat "$c/stderr" 2>/dev/null)"
fi

printf '\n%d passed, %d failed\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
