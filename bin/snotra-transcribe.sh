#!/usr/bin/env bash
# snotra-transcribe.sh — transcribe a meeting recording and produce minutes.
#
# Usage:
#   snotra-transcribe.sh <recording.wav> [topic]
#
# Steps:
#   1. Transcribe the WAV with whisper.cpp (local GPU if available)
#   2. Produce structured minutes in Markdown
#   3. Store minutes under $YMIR_HOME/hodd/workspaces/meetings/
#   4. Append a Rune to the audit ledger
#
# Env:
#   YMIR_HOME          — the hoard root (default ~/Documents/ymirhome)
#   WHISPER_MODEL      — whisper.cpp model path (default: ~/whisper.cpp/models/ggml-small.en.bin)
#   WHISPER_GPU        — use GPU (default: on)
#   RAIL_URL           — llama-swap URL for summaries (default: http://127.0.0.1:8080/v1)
#   RAIL_KEY           — llama-swap API key (from ~/.pi/agent/auth.json)

set -u

YMIR_HOME="${YMIR_HOME:-$HOME/Documents/ymirhome}"
HOARD="$YMIR_HOME/hodd"
MEETINGS="$HOARD/workspaces/meetings"
RUNES="$HOARD/memory/runes_audit.md"
WHISPER_MODEL="${WHISPER_MODEL:-$HOME/whisper.cpp/models/ggml-small.en.bin}"
WHISPER_GPU="${WHISPER_GPU:-on}"
RAIL_URL="${RAIL_URL:-http://127.0.0.1:8080/v1}"
RAIL_KEY="${RAIL_KEY:-}"

mkdir -p "$MEETINGS"

say() { printf '%s\n' "$*"; }

# Resolve the API key from auth.json if not set
if [ -z "$RAIL_KEY" ] && [ -f "$HOME/.pi/agent/auth.json" ]; then
  RAIL_KEY=$(python3 -c 'import json,sys;d=json.load(open(sys.argv[1]));print(d.get("llama-swap",{}).get("key",""))' "$HOME/.pi/agent/auth.json" 2>/dev/null || true)
fi

do_transcribe() {
  local WAV="$1"
  local TOPIC="${2:-meeting}"
  local DATESTAMP
  DATESTAMP=$(date +%Y-%m-%d_%H%M%S)
  local MINUTES_FILE="$MEETINGS/meeting-${DATESTAMP}-minutes.md"

  if [ ! -f "$WAV" ]; then
    echo "error: recording not found: $WAV" >&2
    exit 1
  fi

  say "Transcribing: $WAV"
  say "Topic: $TOPIC"

  # Step 1: Transcribe with whisper.cpp
  local TRANSCRIPT
  if [ -f "$WHISPER_MODEL" ]; then
    say "  whisper.cpp: $WHISPER_MODEL (GPU: $WHISPER_GPU)"
    TRANSCRIPT=$(~/whisper.cpp.main \
      -m "$WHISPER_MODEL" \
      -f "$WAV" \
      -l en \
      --language en \
      --translate 0 \
      --step 5000 \
      --threads 8 \
      --print-progress 0 \
      --outfile /tmp/snotra-transcript.txt 2>/dev/null || true)

    # Read the transcript file
    if [ -f /tmp/snotra-transcript.txt ]; then
      TRANSCRIPT=$(cat /tmp/transcript.txt 2>/dev/null || cat /tmp/snotra-transcript.txt 2>/dev/null || echo "")
    fi
  else
    say "  WARNING: whisper.cpp model not found at $WHISPER_MODEL"
    say "  Falling back to whisper.cpp default (small.en)"
    TRANSCRIPT=$(~/whisper.cpp.main \
      -m "$HOME/whisper.cpp/models/ggml-small.en.bin" \
      -f "$WAV" \
      --language en \
      --outfile /tmp/snotra-transcript.txt 2>/dev/null || true)
    [ -f /tmp/snotra-transcript.txt ] && TRANSCRIPT=$(cat /tmp/snotra-transcript.txt 2>/dev/null || echo "")
  fi

  # Step 2: Produce structured minutes
  local DATE_TODAY
  DATE_TODAY=$(date +%Y-%m-%d)
  local HOUR
  HOUR=$(date +%H:%M)

  cat > "$MINUTES_FILE" <<MINS
# Meeting Minutes — $DATE_TODAY

**Date:** $DATE_TODAY
**Time:** $HOUR
**Topic:** $TOPIC
**Source:** $WAV

## Transcript

$(echo "$TRANSCRIPT" | head -50)

## Decisions

_(pending AI summary)_

## Action Items

_(pending AI summary)_

---
*Generated by Snotra — the meeting ear*
MINS

  say "Minutes written: $MINUTES_FILE"

  # Step 3: Summarize with local rail (if available)
  if [ -n "$RAIL_KEY" ] && [ -n "$TRANSCRIPT" ]; then
    say "  Summarizing with local rail: $RAIL_URL"
    local SUMMARY
    SUMMARY=$(curl -s "$RAIL_URL/chat/completions" \
      -H "Authorization: Bearer $RAIL_KEY" \
      -H "Content-Type: application/json" \
      -d "{
        \"model\": \"qwen3.6-35b-a3b@q2_k_xl\",
        \"messages\": [
          {\"role\": \"system\", \"content\": \"You are a meeting minutes summarizer. Produce concise decisions and action items from the transcript.\"},
          {\"role\": \"user\", \"content\": \"Transcript: $TRANSCRIPT\"}
        ],
        \"temperature\": 0,
        \"max_tokens\": 1000
      }" 2>/dev/null)

    # Extract the summary text
    if [ -n "$SUMMARY" ]; then
      local DECISIONS ACTIONS
      DECISIONS=$(echo "$SUMMARY" | python3 -c '
import json,sys
try:
  d=json.loads(sys.stdin.read())
  text=d.get("choices",[{}])[0].get("message",{}).get("content","")
  print(text)
except: print("")
' 2>/dev/null || echo "")

      if [ -n "$DECISIONS" ]; then
        # Append decisions and action items to the minutes
        {
          echo ""
          echo "## Decisions"
          echo ""
          echo "$DECISIONS" | grep -iE '(decision|decided|agreed|confirmed|approved)' | head -10 || echo "_No explicit decisions captured._"
          echo ""
          echo "## Action Items"
          echo ""
          echo "$DECISIONS" | grep -iE '(action|task|assign|follow up|next)' | head -10 || echo "(none captured)"
          echo ""
          echo "---"
          echo "*Generated by Snotra — the meeting ear*"
        } >> "$MINUTES_FILE"
        say "  Summary appended to minutes"
      fi
    fi
  else
    say "  Skipping summary (no rail key or empty transcript)"
  fi

  # Step 4: Append a Rune
  if command -v ~/ymir/bin/runes-append.sh >/dev/null 2>&1; then
    ~/ymir/bin/runes-append.sh snotra "meeting minutes created — $MINUTES_FILE" --message "snotra: meeting minutes created — $MINUTES_FILE" 2>/dev/null || true
  fi

  say "Done: $MINUTES_FILE"
}

case "${1:-}" in
  -h|--help|"")
    sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'
    ;;
  *)
    do_transcribe "$@"
    ;;
esac
