#!/usr/bin/env bash
# nornir-job-daily-briefing.sh - the 07:00 Sága daily seeing.
#
# Sága sees all that happens. This job writes a real, deterministic daily
# briefing — no model call — from four grounded inputs:
#   1. open forge orders parsed from docs/masterplan.md (append-only source)
#   2. live fleet/state under state/ (cron, metas, status, session lock)
#   3. active plan status from memory/plans/*.md
#   4. today's Runes tail from workspace/memory/runes_audit.md
#
# Output: svartalfaheim/<realm>/workspace/memory/daily/YYYY-MM-DD.md
# It is safe to re-run within a day: the file is rebuilt atomically from the
# same inputs, so the operator never accumulates duplicate briefings.
#
# Environment:
#   BROKK_HOME, BROKK_STATE_OVERRIDE, BROKK_REALM
#   BROKK_BRIEF_DIR          explicit output directory override
#   BROKK_BRIEF_MAX_ORDERS   open orders listed (default 15)
#   BROKK_BRIEF_MAX_RUNES    today's runes listed (default 12)
set -u
# The ONE resolver (Rule 07): env -> the recorded choice -> the one default.
if [ -z "${YMIR_HOARD_LIB_LOADED:-}" ]; then
  for _yc in "${ROOT:-}/bin/hoard-lib.sh" \
             "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." 2>/dev/null && pwd)/bin/hoard-lib.sh" \
             "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." 2>/dev/null && pwd)/bin/hoard-lib.sh" \
             "$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)/hoard-lib.sh"; do
    [ -n "$_yc" ] && [ -r "$_yc" ] && { . "$_yc"; YMIR_HOARD_LIB_LOADED=1; break; }
  done
  unset _yc
fi
if [ -z "${YMIR_HOME:-}" ] && command -v ymir_home_root >/dev/null 2>&1; then
  ymir_home_root YMIR_HOME
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${BROKK_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
BROKK_HOME="${BROKK_HOME:-$ROOT}"
STATE="${BROKK_STATE_OVERRIDE:-$BROKK_HOME/state}"
DATA="${BROKK_DATA_OVERRIDE:-$BROKK_HOME/data}"
# shellcheck source=bin/runes-append.sh
. "$SCRIPT_DIR/runes-append.sh"

REALM="${BROKK_REALM:-}"
if [ -z "$REALM" ] && [ -r "$DATA/realm.md" ]; then
  REALM=$(head -n 1 "$DATA/realm.md" 2>/dev/null | tr -d '[:space:]')
fi
REALM="${REALM:-}"
# Never assume the company's slug: resolve the operator's realm neutrally.
if [ -z "$REALM" ]; then . "$SCRIPT_DIR/realm-lib.sh"; ymir_active_realm "$ROOT" REALM; fi

DATE=$(date +%Y-%m-%d)
BRIEF_DIR="${BROKK_BRIEF_DIR:-${YMIR_HOME}/svartalfaheim/$REALM/workspace/memory/daily}"
BRIEF_FILE="$BRIEF_DIR/$DATE.md"
MAX_ORDERS="${BROKK_BRIEF_MAX_ORDERS:-15}"
MAX_RUNES="${BROKK_BRIEF_MAX_RUNES:-12}"
MASTERPLAN="${BROKK_MASTERPLAN:-${YMIR_HOME}/hodd/docs/masterplan.md}"
PLANS_DIR="${BROKK_PLANS_DIR:-${YMIR_HOME}/memory/plans}"

mkdir -p "$BRIEF_DIR" || { printf 'error: cannot create %s\n' "$BRIEF_DIR"; exit 1; }
TMP="$BRIEF_DIR/.$DATE.md.tmp.$$"
: >"$TMP" || { printf 'error: cannot write %s\n' "$BRIEF_DIR"; exit 1; }
trap 'rm -f "$TMP"' EXIT
emit() { printf '%s\n' "$*" >>"$TMP"; }

# ---- 1. Open forge orders -------------------------------------------------
parse_orders() {
  [ -r "$MASTERPLAN" ] || return 0
  awk '
    /^\*\*W[0-9]+ — / {
      match($0, /W[0-9]+/); id=substr($0, RSTART, RLENGTH);
      title=$0; sub(/^\*\*W[0-9]+ — /, "", title); sub(/\*\*[[:space:]]*$/, "", title);
      next
    }
    /^- Status:/ {
      line=$0; sub(/^- Status:[[:space:]]*/, "", line);
      split(line, a, /[.[:space:]]/); status=a[1];
      if (id != "" && status != "") printf "%s|%s|%s\n", id, status, title;
      id="";
    }
  ' "$MASTERPLAN"
}

emit "# Daily Briefing — $DATE"
emit ""
emit "Realm: \`$REALM\` · Home: \`$BROKK_HOME\` · Generated by Sága (Nornir 07:00, deterministic)"
emit ""
emit "## 1. Open Forge Orders"
emit ""
if [ -r "$MASTERPLAN" ]; then
  orders_tmp="$STATE/.brief-orders.$$"
  mkdir -p "$STATE"
  parse_orders >"$orders_tmp"
  total=$(wc -l <"$orders_tmp" | tr -d '[:space:]')
  added=$(grep -c '|ADDED|' "$orders_tmp" 2>/dev/null || true)
  working=$(grep -c '|WORKING|' "$orders_tmp" 2>/dev/null || true)
  blocked=$(grep -c '|BLOCKED|' "$orders_tmp" 2>/dev/null || true)
  emit "Counts: total=${total:-0} added=${added:-0} working=${working:-0} blocked=${blocked:-0}"
  emit ""
  emit "| Order | Status | Title |"
  emit "|---|---|---|"
  grep -E '\|(ADDED|WORKING|BLOCKED)\|' "$orders_tmp" 2>/dev/null | sort | head -n "$MAX_ORDERS" | while IFS='|' read -r oid ostatus otitle; do
    emit "| $oid | $ostatus | $otitle |"
  done
  if [ "${total:-0}" -gt "$MAX_ORDERS" ]; then
    emit ""
    emit "_(truncated — ${total} open orders total; see hodd/docs/masterplan.md §3)_"
  fi
  rm -f "$orders_tmp"
else
  emit "ABSENT: hodd/docs/masterplan.md not readable"
fi
emit ""

# Active queue (§2) — the published next list.
emit "### Active Queue"
emit ""
if [ -r "$MASTERPLAN" ]; then
  awk '/^## 2\. Active Queue/ {on=1; next} /^## 3\./ {on=0} on && /^[0-9]+\. / {print}' "$MASTERPLAN" \
    | while IFS= read -r q; do emit "- ${q#* }"; done
else
  emit "ABSENT: hodd/docs/masterplan.md not readable"
fi
emit ""

# ---- 2. Fleet & state -----------------------------------------------------
emit "## 2. Fleet & State"
emit ""
if [ -x "$SCRIPT_DIR/nornir-cron-start.sh" ]; then
  cron_line=$(BROKK_HOME="$BROKK_HOME" BROKK_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/nornir-cron-start.sh" --status 2>/dev/null || printf 'cron: status unavailable')
  emit "- ${cron_line:-cron: status unavailable}"
else
  emit "- cron: scheduler not installed"
fi
if [ -r "$STATE/.lock" ]; then
  lock_owner=$(tr -d '[:space:]' <"$STATE/.lock")
  if [ -n "$lock_owner" ] && kill -0 "$lock_owner" 2>/dev/null; then
    emit "- session lock: held by pid $lock_owner (live)"
  else
    emit "- session lock: stale pid ${lock_owner:-empty}"
  fi
else
  emit "- session lock: none (read-only would apply)"
fi
meta_count=$(find "$STATE" -maxdepth 1 -name '*.meta' 2>/dev/null | wc -l | tr -d '[:space:]')
status_count=$(find "$STATE" -maxdepth 1 -name '*.status' 2>/dev/null | wc -l | tr -d '[:space:]')
emit "- task metadata records: ${meta_count:-0}"
emit "- status records: ${status_count:-0}"
if [ "$meta_count" != "0" ]; then
  find "$STATE" -maxdepth 1 -name '*.meta' 2>/dev/null | sort | while IFS= read -r m; do
    emit "  - $(basename "$m"): $(head -n 1 "$m" 2>/dev/null)"
  done
fi
if [ -r "${YMIR_HOME}/svartalfaheim/$REALM/.env.realm" ]; then
  emit "- realm env: present"
else
  emit "- realm env: ABSENT (svartalfaheim/$REALM/.env.realm)"
fi
emit ""

# ---- 3. Active plan status ------------------------------------------------
emit "## 3. Active Plan Status"
emit ""
if [ -d "$PLANS_DIR" ]; then
  for plan in "$PLANS_DIR"/*.md; do
    [ -r "$plan" ] || continue
    pname=$(basename "$plan" .md)
    [ "$pname" = "README" ] && continue
    pstatus=$(grep -m1 -i 'status' "$plan" 2>/dev/null | sed -E 's/^.*[Ss]tatus[*:[:space:]]*//; s/[[:space:]]*$//')
    emit "- \`$pname\` — ${pstatus:-unknown}"
  done
else
  emit "ABSENT: memory/plans/ not readable"
fi
emit ""

# ---- 4. Today's Runes tail ------------------------------------------------
emit "## 4. Today's Runes (${DATE})"
emit ""
runes_file_path runes_path
if [ -r "$runes_path" ]; then
  today_runes=$(grep -F "\"timestamp\":\"$DATE" "$runes_path" 2>/dev/null | tail -n "$MAX_RUNES")
  if [ -n "$today_runes" ]; then
    emit '```jsonl'
    printf '%s\n' "$today_runes" >>"$TMP"
    emit '```'
  else
    emit "No Runes carved today yet."
  fi
else
  emit "ABSENT: $runes_path"
fi
emit ""

# ---- Next step ------------------------------------------------------------
emit "## Next"
emit ""
emit "Begin from the Active Queue above. Frontend gate stays ahead of backend (plan 29 §0)."

mv "$TMP" "$BRIEF_FILE" || { printf 'error: cannot publish %s\n' "$BRIEF_FILE"; exit 1; }
trap - EXIT
printf 'briefing: wrote %s (%s bytes)\n' "$BRIEF_FILE" "$(wc -c <"$BRIEF_FILE" | tr -d '[:space:]')"

runes_append "nornir" "briefing.written" --realm "$REALM" \
  --message "daily briefing for $DATE written to $BRIEF_FILE" >/dev/null || printf 'briefing: rune append failed (non-fatal)\n'
