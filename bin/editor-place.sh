#!/usr/bin/env bash
# editor-place.sh — the editor opens on its OWN desktop, never on yours.
#
# The Allfather reads and works on a desktop. An editor that maps on top of that
# steals the place he was in. So the editor gets a desktop of its own, exactly as
# the Ymir apps do (bin/desktop-place.sh) — and it uses the SAME mechanism, which
# is the one proven on this machine:
#
#   Hyprland applies window rules at MAP time, so the window never appears on the
#   working desktop at all. Writing `o.window({ class = ... }, { workspace = ... })`
#   into ~/.config/hypr/ymir-desktops.lua and reloading is strictly better than
#   moving a window after it has already appeared.
#
# (The runtime dispatch form — `hyprctl dispatch movetoworkspacesilent 5,class:...`
# does NOT work on this Hyprland 0.56, which replaced it with a Lua API. The rule
# file is the road that holds.)
#
# Usage:
#   bin/editor-place.sh plan             # which desktop the editor would take
#   bin/editor-place.sh apply [--dry-run]# write the rule + reload
#   bin/editor-place.sh status
#   bin/editor-place.sh --version
#
# Env: YMIR_EDITOR_CLASS (default: the resolved editor, else `code`)
set -u

VERSION="1.0.0"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
HYPR_DIR="$HOME/.config/hypr"
RULE_FILE="$HYPR_DIR/ymir-desktops.lua"
DRY=0

case "${1-}" in
  -v|-V|--version) printf '%s\n' "$VERSION"; exit 0 ;;
  -h|--help|"") sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
esac
ACTION="${1:-plan}"; shift || true
[ "${1:-}" = "--dry-run" ] && DRY=1

have() { command -v "$1" >/dev/null 2>&1; }

# The editor's window class, as Hyprland reports it.
editor_class() {
  local bin="${YMIR_EDITOR:-}"
  if [ -z "$bin" ]; then
    for e in code cursor zed subl nvim vim; do have "$e" && { bin="$e"; break; }; done
  fi
  case "$(basename "${bin:-code}")" in
    code|code-insiders|codium) printf 'code' ;;
    cursor) printf 'cursor' ;;
    zed) printf 'dev\\.zed\\.Zed' ;;
    subl|sublime_text) printf 'sublime_text' ;;
    *) printf '%s' "${bin:-code}" ;;
  esac
}

free_desktop() {
  have hyprctl || return 1
  hyprctl workspaces -j 2>/dev/null | python3 -c '
import json,sys
try:
    d=json.load(sys.stdin)
except Exception:
    sys.exit(0)
used={w.get("id") for w in d if w.get("windows",0)>0}
for n in range(1,11):
    if n not in used:
        print(n); break
' 2>/dev/null
}

# Read the desktops already claimed in the rule file, so we do not collide with
# the apps (or the editor, on a re-run).
claimed_desktops() {
  [ -r "$RULE_FILE" ] || return 0
  grep -oE 'workspace = "[0-9]+"' "$RULE_FILE" 2>/dev/null | grep -oE '[0-9]+' | sort -n -u
}

plan_desktop() {
  local cls; cls="$(editor_class)"
  # If the editor already has a rule AND that desktop is not claimed by the apps
  # (nor holding their windows), keep it — stability matters. If it collides with
  # an app, fall through and pick a truly free desktop.
  local app_claims=""
  if [ -x "$SCRIPT_DIR/desktop-place.sh" ]; then
    app_claims="$("$SCRIPT_DIR/desktop-place.sh" plan 2>/dev/null | tail -n +2 \
      | sed -nE 's/.*,([0-9]+)$/\1/p' | tr '\n' ' ')"
  fi
  if [ -r "$RULE_FILE" ]; then
    local existing
    existing="$(grep -E "class = \"\^${cls}\\\$" "$RULE_FILE" 2>/dev/null | grep -oE 'workspace = "[0-9]+"' | grep -oE '[0-9]+' | head -1)"
    if [ -n "$existing" ]; then
      local collides=0
      for a in $app_claims; do [ "$a" = "$existing" ] && collides=1; done
      [ "$collides" = 0 ] && { printf '%s' "$existing"; return 0; }
    fi
  fi
  python3 - "$app_claims" <<'PY'
import sys, subprocess, json
used = {int(x) for x in sys.argv[1].split() if x.isdigit()}
try:
    d = json.loads(subprocess.run(["hyprctl","workspaces","-j"],capture_output=True,text=True).stdout)
    for w in d:
        if w.get("windows",0) > 0:
            used.add(w.get("id"))
except Exception:
    pass
for n in range(1, 13):
    if n not in used:
        print(n); break
else:
    print(1)
PY
}

write_rule() {  # <desktop>
  local d=$1 cls
  cls="$(editor_class)"
  local header='-- Ymir desktop placement (generated by bin/desktop-place.sh + bin/editor-place.sh).
-- On Omarchy the numbered desktops are the operator'"'"'s "screens".
-- Each Ymir window opens on its own desktop, preferring an EMPTY one, and is
-- placed at MAP time so it never appears on the desktop you are working on.
-- Regenerate with: bin/desktop-place.sh apply && bin/editor-place.sh apply

'
  local applines=""
  # Preserve the app rules by reading desktop-place.sh's own plan and rewriting
  # them in the SAME file, so one file owns every Ymir window placement. Rows
  # look like:  "hlidskjalf",5
  if [ -x "$SCRIPT_DIR/desktop-place.sh" ]; then
    applines="$(
      "$SCRIPT_DIR/desktop-place.sh" plan 2>/dev/null | tail -n +2 |
      while IFS= read -r row; do
        app="$(printf '%s' "$row" | sed -nE 's/^ *"([a-z]+)",.*/\1/p')"
        num="$(printf '%s' "$row" | sed -nE 's/.*,([0-9]+)$/\1/p')"
        [ -n "$app" ] && [ -n "$num" ] || continue
        case "$app" in
          hlidskjalf) printf 'o.window({ class = "^ymir-hlidskjalf$" }, { workspace = "%s" })\n' "$num" ;;
          smidja)     printf 'o.window({ class = "^ymir-smidja$" }, { workspace = "%s" })\n' "$num" ;;
        esac
      done
    )"
  fi
  local editorline
  # `no_focus = true` is Omarchy's own idiom (default/hypr/windows.lua) for mapping
  # a window without stealing focus. `workspace` sends it to its own desktop; the
  # pair means the editor appears where it belongs and the Allfather keeps the
  # desk he was reading at.
  editorline="$(printf 'o.window({ class = "^%s$" }, { workspace = "%s", no_focus = true })\n' "$cls" "$d")"
  if [ "$DRY" = 1 ]; then
    printf '%s' "$header"
    [ -n "$applines" ] && printf '%s\n' "$applines"
    printf '%s' "$editorline"
    return 0
  fi
  mkdir -p "$HYPR_DIR"
  {
    printf '%s' "$header"
    # Command substitution strips the trailing newline, so re-add the separator.
    [ -n "$applines" ] && printf '%s\n' "$applines"
    printf '%s' "$editorline"
  } >"$RULE_FILE"
}

include_rule_file() {
  local main="$HYPR_DIR/hyprland.lua"
  local line='require("hypr.ymir-desktops")'
  [ -f "$main" ] || return 0
  grep -qxF "$line" "$main" && return 0
  [ "$DRY" = 1 ] && { printf 'would add to %s: %s\n' "$main" "$line"; return 0; }
  printf '\n-- Ymir: place the desktop windows on their own desktops.\n%s\n' "$line" >>"$main"
}

case "$ACTION" in
  plan)
    cls="$(editor_class)"; d="$(plan_desktop)"
    printf 'editor-place[1]{class,desktop}:\n  "%s",%s\n' "$cls" "$d"
    ;;
  apply)
    have hyprctl || { printf 'editor-place[1]{state}:\n  "skipped — no hyprctl (not a Hyprland host)"\n'; exit 0; }
    d="$(plan_desktop)"
    write_rule "$d"
    include_rule_file
    if [ "$DRY" != 1 ]; then
      # Validate, per the Omarchy guide: reload then check for config errors.
      hyprctl reload >/dev/null 2>&1 || true
      errs="$(hyprctl configerrors 2>&1 | head -3)"
      if [ -n "$errs" ]; then
        printf 'editor-place[1]{state,desktop,configerrors}:\n  "written, but Hyprland reported errors","%s","%s"\n' "$d" "$(printf '%s' "$errs" | tr '\n' ' ')"
        exit 1
      fi
      printf 'editor-place[1]{state,class,desktop}:\n  "written","%s","%s"\n' "$(editor_class)" "$d"
    else
      printf 'editor-place[1]{state,desktop}:\n  "dry-run","%s"\n' "$d"
    fi
    ;;
  status)
    if [ -r "$RULE_FILE" ]; then
      printf 'editor-place[1]{file}:\n  "%s"\n' "$RULE_FILE"
      grep -E 'class = ' "$RULE_FILE" 2>/dev/null | sed 's/^/  /' || true
    else
      printf 'editor-place[1]{state}:\n  "no rule file yet"\n'
    fi
    ;;
  *) printf 'error: unknown action %s\nhelp: bin/editor-place.sh [plan|apply|status]\n' "$ACTION" >&2; exit 2 ;;
esac
