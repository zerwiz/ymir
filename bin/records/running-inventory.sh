#!/usr/bin/env bash
# running-inventory.sh — what is actually running on this machine, generated rather than remembered.
#
# Why (his word, 2026-11-14): *"we need to have a list of all containers and things we're running — don't we have
# that?"* We did not. The home carried a server layout written once by hand, and a container list existed only in
# whatever session happened to run `docker ps`. A machine that cannot list what it runs cannot answer "what is this
# using?" or "what can I stop?" — and this one has been asked both questions all night.
#
#   running-inventory.sh            write the inventory for this host (yaml + markdown), print a summary
#   running-inventory.sh --stdout   print the yaml, write nothing
#
# Written to: $YMIR_HOME/hodd/machines/<host>/running.{yaml,md}
# The yaml is the record (parsed by other doors); the markdown is the page a person reads.
set -uo pipefail

# The home is resolved, never assumed (RULES/07): the one resolver is bin/vault/hoard-lib.sh.
_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_ROOT="$(cd "$_DIR" && while [ ! -d "$PWD/RULES" ] || [ ! -d "$PWD/bin" ]; do [ "$PWD" = / ] && break; cd ..; done; pwd)"
if [ -z "${YMIR_HOME:-}" ] && [ -r "$_ROOT/bin/vault/hoard-lib.sh" ]; then
  . "$_ROOT/bin/vault/hoard-lib.sh" >/dev/null 2>&1 || true
  if command -v ymir_home_root >/dev/null 2>&1; then _h=""; ymir_home_root _h; [ -n "$_h" ] && export YMIR_HOME="$_h"; fi
fi
[ -n "${YMIR_HOME:-}" ] || { printf '%s: the home could not be resolved (bin/vault/hoard-lib.sh, RULES/07)\n' "$(basename "$0")" >&2; exit 2; }
HOME_DIR="${YMIR_HOME}"
HOST="$(hostname -s 2>/dev/null || hostname)"
OUT="$HOME_DIR/hodd/machines/$HOST"
OUT_YAML="$OUT/running.yaml"
OUT_MD="$OUT/running.md"
STDOUT_ONLY=0
[ "${1:-}" = "--stdout" ] && STDOUT_ONLY=1

command -v docker >/dev/null 2>&1 || { printf 'running-inventory: docker not present — this host runs no containers\n' >&2; }

yaml_escape() { printf '%s' "$1" | sed 's/"/\\"/g'; }

emit() {
  local now; now="$(date -u +%FT%TZ)"
  printf '# generated by bin/records/running-inventory.sh — do not hand-edit\n'
  printf 'host: %s\n' "$HOST"
  printf 'generated: %s\n' "$now"
  printf 'kernel: %s\n' "$(uname -r)"
  printf 'memory_mb: %s\n' "$(awk '/MemTotal/{printf "%d", $2/1024}' /proc/meminfo)"
  printf 'load: "%s"\n' "$(cut -d' ' -f1-3 /proc/loadavg)"
  printf 'containers:\n'
  if command -v docker >/dev/null 2>&1; then
    docker ps -a --format '{{.Names}}' 2>/dev/null | sort | while IFS= read -r name; do
      [ -z "$name" ] && continue
      local info; info="$(docker inspect "$name" --format \
        '{{.State.Status}}|{{.Config.Image}}|{{index .Config.Labels "com.docker.compose.project"}}|{{index .Config.Labels "com.docker.compose.project.working_dir"}}|{{.HostConfig.RestartPolicy.Name}}|{{.HostConfig.Memory}}' 2>/dev/null)"
      IFS='|' read -r status image project workdir restart memlimit <<<"$info"
      local ports; ports="$(docker port "$name" 2>/dev/null | tr '\n' ' ' | sed 's/  */ /g')"
      printf '  - name: %s\n' "$name"
      printf '    status: %s\n' "${status:-unknown}"
      printf '    image: "%s"\n' "$(yaml_escape "${image:-?}")"
      printf '    project: "%s"\n' "$(yaml_escape "${project:-standalone}")"
      [ -n "${workdir:-}" ] && printf '    compose_dir: "%s"\n' "$(yaml_escape "$workdir")"
      printf '    restart: %s\n' "${restart:-no}"
      printf '    memory_limit_bytes: %s\n' "${memlimit:-0}"
      [ -n "${ports:-}" ] && printf '    ports: "%s"\n' "$(yaml_escape "$ports")"
    done
  fi
  printf 'published_ports:\n'
  ss -ltn 2>/dev/null | awk 'NR>1{split($4,a,":"); p=a[length(a)]; print p"\t"$4}' | sort -u -k1,1n | \
    while IFS=$'\t' read -r p addr; do printf '  - port: %s\n    addr: "%s"\n' "$p" "$addr"; done
  printf 'units_active:\n'
  { systemctl list-units --type=service --state=running --no-legend --no-pager 2>/dev/null | awk '{print $1}';
    systemctl --user list-units --type=service --state=running --no-legend --no-pager 2>/dev/null | awk '{print $1}'; } | \
    sed 's/\.service$//' | sort -u | grep -vE '^(dbus|systemd|user@|gpg|polkit|snapd|udisks|upower|cron\.|ssh\.)' | \
    while IFS= read -r u; do printf '  - "%s"\n' "$(yaml_escape "$u")"; done
  printf 'tunnels:\n'
  pgrep -af "cloudflared tunnel" 2>/dev/null | grep -oE 'config-[a-z-]+\.yml' | sed 's/config-//;s/\.yml//' | sort -u | \
    while IFS= read -r t; do printf '  - "%s"\n' "$(yaml_escape "$t")"; done
}

if [ "$STDOUT_ONLY" -eq 1 ]; then
  emit
  exit 0
fi

mkdir -p "$OUT"
tmp="$(mktemp)"; emit > "$tmp"
mv "$tmp" "$OUT_YAML"

# the page a person reads
{
  printf '# %s — what is running (generated %s)\n\n' "$HOST" "$(date -u +%FT%TZ)"
  printf 'Memory %s MB · load %s\n\n' "$(awk '/MemTotal/{printf "%d", $2/1024}' /proc/meminfo)" "$(cut -d' ' -f1-3 /proc/loadavg)"
  printf '| container | status | image | project | ports |\n|---|---|---|---|---|\n'
  docker ps -a --format '{{.Names}}' 2>/dev/null | sort | while IFS= read -r name; do
    docker inspect "$name" --format '{{.State.Status}}|{{.Config.Image}}|{{index .Config.Labels "com.docker.compose.project"}}' 2>/dev/null | \
      awk -F'|' -v n="$name" -v p="$(docker port "$name" 2>/dev/null | tr '\n' ' ' | cut -c1-40)" \
        '{printf "| %s | %s | %s | %s | %s |\n", n, $1, $2, ($3==""?"standalone":$3), p}'
  done
  printf '\n## ports held\n\n'
  ss -ltn 2>/dev/null | awk 'NR>1{split($4,a,":"); print a[length(a)]}' | sort -un | paste -sd' '
  printf '\n\nGenerated by `bin/records/running-inventory.sh`; never hand-edited.\n'
} > "$OUT_MD"

c=$(docker ps -q 2>/dev/null | wc -l)
a=$(docker ps -aq 2>/dev/null | wc -l)
u=$(systemctl list-units --type=service --state=running --no-legend 2>/dev/null | wc -l)
printf 'running-inventory: %s — %s of %s containers running, %s system services, written to %s\n' "$HOST" "$c" "$a" "$u" "$OUT"
