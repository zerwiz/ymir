#!/usr/bin/env bash
# tunnels-registry.sh — emit the registry's `tunnels:` block from the cloudflared configs that actually exist.
#
# His word (2026-11-14): "we need to list all tunnels we have in the registry." A tunnel known only as a file in a home
# directory is a tunnel nobody can audit — and this machine had 29 of them, several serving nothing.
#
#   tunnels-registry.sh            print the yaml block (paste into hodd/identity/services.yaml, or pipe to a file)
#   tunnels-registry.sh --apply    rewrite the block in services.yaml in place (between the markers below)
#
# What is measured here: the config file, the tunnel id it declares, its hostnames, its upstreams, and whether a process
# is running with that config. Whether each name ANSWERS is measured separately by tunnels-status.sh.
set -uo pipefail
CD="${CLOUDFLARED_DIR:-$HOME/.cloudflared}"
HOME_DIR="${YMIR_HOME:-$HOME/Documents/ymirhome}"
REG="$HOME_DIR/hodd/identity/services.yaml"

block=$(python3 - "$CD" <<'PY'
import glob, re, os, sys, subprocess
cd=sys.argv[1]
rows=[]
for cfg in sorted(glob.glob(os.path.join(os.path.expanduser(cd),'config*.yml'))):
    txt=open(cfg, encoding='utf-8', errors='ignore').read()
    name=os.path.basename(cfg).replace('config-','').replace('.yml','')
    tid=re.search(r'^tunnel:\s*(\S+)', txt, re.M)
    hosts=re.findall(r'hostname:\s*(\S+)', txt)
    svcs=[s for s in re.findall(r'service:\s*(\S+)', txt) if not s.startswith('http_status')]
    running=subprocess.run(['pgrep','-f',os.path.basename(cfg)],capture_output=True).returncode==0
    rows.append((name, os.path.basename(cfg), tid.group(1) if tid else '', hosts, sorted(set(svcs)), running))
print('# ─────────────────────────────── THE TUNNELS, all of them (generated) ───────────────────────────────')
print('# Generated by bin/records/tunnels-registry.sh from ~/.cloudflared/config*.yml — do not hand-edit; re-run it.')
print('# `running` is the process; whether each name ANSWERS is measured by bin/records/tunnels-status.sh. A tunnel whose')
print('# upstreams are gone is a DECISION (raise the service or lower the tunnel), never weather.')
print('tunnels:')
for name,cfg,tid,hosts,svcs,running in rows:
    print(f'  - tunnel: {name}')
    print(f'    config: "~/.cloudflared/{cfg}"')
    if tid: print(f'    tunnel_id: {tid}')
    print(f'    running: {str(running).lower()}')
    print(f'    hostnames: [{", ".join(hosts)}]')
    if svcs: print(f'    upstreams: [{", ".join(svcs)[:200]}]')
PY
)

if [ "${1:-}" = "--apply" ]; then
  python3 - "$REG" <<PY
import sys
reg=sys.argv[1]
s=open(reg).read()
start=s.find('# ─────────────────────────────── THE TUNNELS')
block='''$block
'''
if start>=0:
    s=s[:start]+block
else:
    s=s.rstrip()+'\n\n'+block
open(reg,'w').write(s)
print('rewrote the tunnels block in', reg)
PY
else
  printf '%s\n' "$block"
fi
