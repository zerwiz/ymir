#!/usr/bin/env bash
# gladsheim-ensure.sh — seat the fleet room, whatever shape this machine is.
#
# The room's engine (continuwuity, the maintained Conduit continuation) runs ONCE per
# operator install. WHICH machine that is depends on the SHAPE (plan 76 — the shape law):
#
#   single machine  → the engine runs HERE, and this machine is also the client
#   fleet           → the engine runs ON THE HEART; every other seat is a CLIENT only
#
# So this script asks bin/fleet/topology.sh (never re-derives), seats the role the shape
# implies, and SKIPS CLEANLY where the role does not apply — a seat must never raise a
# second homeserver.
#
#   gladsheim-ensure.sh status           # what is seated, and what this machine's role is
#   gladsheim-ensure.sh ensure [--install]  # seat it (--install may pull the image)
#
# Configuration is resolved from the operator's home (Rule 07), the token is a SECRET BY
# REFERENCE (Rule 04), and the bootstrap token is PINNED before first boot — the live
# proof (2026-10-12) showed a generated registration token changes across restarts, so an
# installer that reads it from a log is racing the server.
#
# THE ONE GOTCHA, MEASURED (2026-10-12, on the heart): continuwuity IGNORES the configured
# `registration_token` until the FIRST account exists. It prints its own first-boot token,
# which is the ONLY one that works for that first account; from the second account onward
# the pinned token governs. So the bootstrap sequence is:
#
#   1. the engine comes up and prints a first-boot token (or the admin console creates user 1)
#   2. create the OPERATOR's account with that token
#   3. from then on the pinned ROOM_BOOTSTRAP_TOKEN registers every agent
#
#   gladsheim-ensure.sh bootstrap   # prints the first-boot token and what to do with it
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${BROKK_ROOT_OVERRIDE:-$(CDPATH='' cd "$SCRIPT_DIR" && while [ ! -d .pi ] || [ ! -d RULES ]; do [ "$PWD" = / ] && break; cd ..; done; pwd)}"

if [ -z "${YMIR_HOARD_LIB_LOADED:-}" ]; then
  for _c in "$SCRIPT_DIR/../vault/hoard-lib.sh" "$SCRIPT_DIR/../../vault/hoard-lib.sh"; do
    [ -r "$_c" ] && { . "$_c"; YMIR_HOARD_LIB_LOADED=1; break; }
  done
fi
HOME_ROOT="${YMIR_HOME:-}"; command -v ymir_home_root >/dev/null 2>&1 && ymir_home_root HOME_ROOT
STATE_DIR="${YMIR_GLADSHEIM_STATE:-${YMIR_STATE_DIR:-$HOME_ROOT/state}/gladsheim}"
CONFIG="$HOME_ROOT/config/room.yaml"
SECRETS="${YMIR_GLADSHEIM_SECRETS:-$HOME_ROOT/hodd/secrets/room.env}"
IMAGE="${YMIR_GLADSHEIM_IMAGE:-ghcr.io/continuwuity/continuwuity:latest}"
CONTAINER="${YMIR_GLADSHEIM_CONTAINER:-gladsheim-engine}"
PORT="${YMIR_GLADSHEIM_PORT:-8008}"

ACTION="${1:-status}"; shift || true
INSTALL=0; [ "${1:-}" = "--install" ] && INSTALL=1

# ── the shape, ASKED of the one resolver (plan 76) ───────────────────────────
SHAPE="single"; ROLES="dev"; HEART=""; LINK="standalone"
_topo="$ROOT/bin/fleet/topology.sh"; [ -r "$_topo" ] || _topo="$SCRIPT_DIR/../fleet/topology.sh"
if [ -r "$_topo" ]; then
  _j="$(timeout 15 bash "$_topo" --json 2>/dev/null || true)"
  if [ -n "$_j" ]; then
    SHAPE="$(printf '%s' "$_j" | python3 -c 'import json,sys;print(json.load(sys.stdin).get("shape","single"))' 2>/dev/null || echo single)"
    ROLES="$(printf '%s' "$_j" | python3 -c 'import json,sys;print(",".join(json.load(sys.stdin).get("roles") or []))' 2>/dev/null || echo dev)"
    HEART="$(printf '%s' "$_j" | python3 -c 'import json,sys;print(json.load(sys.stdin).get("heart") or "")' 2>/dev/null || echo "")"
    LINK="$(printf '%s' "$_j" | python3 -c 'import json,sys;print(json.load(sys.stdin).get("link","standalone"))' 2>/dev/null || echo standalone)"
  fi
fi

# Does THIS machine hold the engine? single → yes; fleet → only a heart role.
HOST="$(hostname -s)"
ENGINE_HERE=1
if [ "$SHAPE" = "fleet" ]; then
  ENGINE_HERE=0
  case ",$ROLES," in *,heart,*) ENGINE_HERE=1 ;; esac
  [ -n "$HEART" ] && [ "$HEART" = "$HOST" ] && ENGINE_HERE=1
fi

engine_up() { curl -s --max-time 5 "http://127.0.0.1:$PORT/_matrix/client/versions" >/dev/null 2>&1; }

pinned_token() {  # the bootstrap token, PINNED — generate once, then never again
  t=""
  [ -r "$SECRETS" ] && t="$(grep -oP '^ROOM_BOOTSTRAP_TOKEN=\K.*' "$SECRETS" 2>/dev/null | tail -1)"
  printf '%s' "$t"
}

write_config() {  # the engine's own config — only on the machine that holds the engine
  mkdir -p "$STATE_DIR/data"
  tok="$(pinned_token)"
  cat > "$STATE_DIR/conduwuit.toml" <<EOF
# Gladsheim's engine (continuwuity). Generated by gladsheim-ensure.sh — runtime config,
# lives in the hoard's state, never in the repo. The bootstrap token is PINNED so an
# install is deterministic (a generated one changes across restarts).
[global]
server_name = "${YMIR_GLADSHEIM_SERVER_NAME:-gladsheim.local}"
database_path = "/var/lib/conduwuit"
address = "0.0.0.0"
port = $PORT
allow_registration = true
allow_federation = ${YMIR_GLADSHEIM_FEDERATION:-false}
registration_token = "$tok"
EOF
}

case "$ACTION" in
  bootstrap)
    # The first account's token is the engine's own, not the pinned one (measured 2026-10-12).
    # Print it, and say plainly what to do with it.
    [ "$ENGINE_HERE" = 1 ] || { printf 'gladsheim-ensure: this seat holds no engine — the token is on the heart%s\n' "${HEART:+ ($HEART)}"; exit 0; }
    tok="$(docker logs "$CONTAINER" 2>&1 | sed 's/\x1b\[[0-9;]*m//g' | grep -oE 'registration token [A-Za-z0-9]{16}' | tail -1 | awk '{print $3}')"
    printf 'gladsheim-bootstrap[3]{fact,value}:\n'
    printf '  "first_user_token","%s"\n' "${tok:-none — is the engine running?}"
    printf '  "use_for","the OPERATOR account ONLY (the first user)"\n'
    printf '  "after_that","the pinned token in %s registers every agent"\n' "$SECRETS"
    ;;
  status)
    up="down"; engine_up && up="up"
    printf 'gladsheim-ensure[7]{fact,value}:\n'
    printf '  "shape","%s"\n' "$SHAPE"
    printf '  "roles","%s"\n' "$ROLES"
    printf '  "heart","%s"\n' "${HEART:-none}"
    printf '  "this_machine","%s"\n' "$HOST"
    printf '  "holds_engine","%s"\n' "$([ "$ENGINE_HERE" = 1 ] && echo yes || echo no)"
    printf '  "engine","%s"\n' "$up"
    printf '  "config_seated","%s"\n' "$([ -r "$CONFIG" ] && echo yes || echo no)"
    ;;
  ensure)
    # THE DOOR IS NARROW ON PURPOSE (the gate law, plan 75 Part 13): the HOST side publishes
    # on the tailnet interface only (or loopback with no tailnet), never 0.0.0.0 — the LAN
    # must not be a door. Inside the container the engine still hears 0.0.0.0 (docker's
    # published port is what narrows it); binding the in-container address to a tailnet IP
    # makes the service UNREACHABLE, because that address does not exist in the container.
    BIND="127.0.0.1"
    command -v tailscale >/dev/null 2>&1 && BIND="$(tailscale ip -4 2>/dev/null | head -1)"
    [ -n "$BIND" ] || BIND="127.0.0.1"
    if [ "$ENGINE_HERE" = 0 ]; then
      # A SEAT: a client only — but a client must still be ABLE to speak, so this is a real
      # door-check, not a shrug. Report what the seat has and what it is missing, because a
      # seat that cannot name its room or hold its token is a seat that silently cannot talk.
      [ "$INSTALL" = 1 ] && printf 'gladsheim: this seat is a client — the engine belongs to the heart (%s); not raising a second homeserver\n' "${HEART:-?}"
      cfg="${HOME_ROOT}/config/room.yaml" sec="${HOME_ROOT}/hodd/secrets/room.env"
      hs="" rm="" ag="" tk="no" reach="down"
      if [ -r "$cfg" ]; then
        eval "$(python3 - "$cfg" "$(hostname -s)" <<'PY'
import sys
cfg, host = sys.argv[1], sys.argv[2]
doc = {}; cur = None
for line in open(cfg):
    line = line.split('#', 1)[0].rstrip()
    if not line.strip():
        continue
    if line[:1] in (' ', '\t'):
        if cur == 'agents' and ':' in line:
            k, _, v = line.strip().partition(':')
            doc['agents'][k.strip()] = v.strip().strip('"')
        continue
    k, _, v = line.partition(':')
    cur = k.strip()
    if cur == 'agents':
        doc['agents'] = {}
    else:
        doc[cur] = v.strip().strip('"')
print('hs=%s' % (doc.get('homeserver') or ''))
print('rm=%s' % (doc.get('room') or ''))
print('ag=%s' % ((doc.get('agents') or {}).get(host, '')))
PY
)"
      fi
      [ -r "$sec" ] && grep -q '^ROOM_ACCESS_TOKEN=..' "$sec" 2>/dev/null && tk="yes"
      [ -n "$hs" ] && { curl -s --max-time 5 "$hs/_matrix/client/versions" >/dev/null 2>&1 && reach="up"; }
      missing=""
      [ -r "$cfg" ] || missing="$missing config"
      [ -n "$hs" ] || missing="$missing homeserver"
      [ -n "$rm" ] || missing="$missing room"
      [ -n "$ag" ] || missing="$missing agent-name"
      [ "$tk" = yes ] || missing="$missing token"
      printf 'gladsheim-ensure[6]{fact,result}:\n'
      printf '  "role","client (seat)"\n'
      printf '  "engine","skip — held by the heart%s"\n' "${HEART:+ ($HEART)}"
      printf '  "agent","%s"\n' "${ag:-unnamed}"
      printf '  "homeserver","%s"\n' "${hs:-none}"
      printf '  "reachable","%s"\n' "$reach"
      printf '  "token","%s"\n' "$tk"
      printf '  "missing","%s"\n' "${missing:-nothing — this seat can speak}"
      [ -z "$missing" ] && [ "$reach" = up ] || exit 1
      exit 0
    fi
    # THE ENGINE HOLDER (a lone box, or the heart)
    if ! command -v docker >/dev/null 2>&1; then
      printf 'gladsheim-ensure[1]{fact,result}:\n  "engine","skip — no docker on this machine"\n'; exit 0
    fi
    mkdir -p "$(dirname "$SECRETS")"; [ -r "$SECRETS" ] || : > "$SECRETS"
    chmod 600 "$SECRETS" 2>/dev/null || true
    if [ -z "$(pinned_token)" ]; then
      tok="$(openssl rand -hex 12 2>/dev/null || head -c 12 /dev/urandom | od -An -tx1 | tr -d ' \n')"
      printf 'ROOM_BOOTSTRAP_TOKEN=%s\n' "$tok" >> "$SECRETS"
    fi
    write_config
    if [ "$INSTALL" = 1 ]; then docker pull -q "$IMAGE" >/dev/null 2>&1 || true; fi
    docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
    # BOTH loopback and the tailnet: loopback so the host's own tools (and a local tunnel)
    # reach it; the tailnet so the fleet does; NEVER 0.0.0.0, so the LAN is not a door.
    if docker run -d --name "$CONTAINER" -p "127.0.0.1:$PORT:$PORT" -p "$BIND:$PORT:$PORT" \
        -v "$STATE_DIR/conduwuit.toml:/etc/conduwuit/conduwuit.toml:ro" \
        -v "$STATE_DIR/data:/var/lib/conduwuit" \
        --restart unless-stopped "$IMAGE" /sbin/conduwuit -c /etc/conduwuit/conduwuit.toml >/dev/null 2>&1; then
      sleep 4; engine_up && st="up" || st="starting"
      printf 'gladsheim-ensure[3]{fact,result}:\n'
      printf '  "role","engine"\n'
      printf '  "container","%s"\n' "$CONTAINER"
      printf '  "reachable_at","%s:%s (tailnet/loopback only — never the LAN)"\n' "$BIND" "$PORT"
      printf '  "engine","%s"\n' "$st"
      printf '  "bootstrap_token","pinned in %s"\n' "$SECRETS"
    else
      printf 'gladsheim-ensure[1]{fact,result}:\n  "engine","FAILED to run — docker run returned non-zero"\n'; exit 1
    fi
    ;;
  *) printf 'gladsheim-ensure: unknown action %s (status | ensure)\n' "$ACTION" >&2; exit 2 ;;
esac
