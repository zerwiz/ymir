#!/usr/bin/env bash
# gjallarhorn-expose.sh — put EVERY app on its own public hostname (Gjallarhorn).
#
# The dev machine wears the name; the server does not. So the hostnames carry a
# machine suffix (`dell` here) and this script refuses to run without one — a
# server must never acquire the laptop's names.
#
#   bin/gjallarhorn-expose.sh plan     # the hostnames and where each points
#   bin/gjallarhorn-expose.sh apply    # write the config, create the routes, raise the tunnel
#   bin/gjallarhorn-expose.sh status   # what is exposed right now
#
# Hostnames come from the apps this machine actually serves (a port that answers)
# plus YMIR_TUNNEL_SUFFIX: <app><suffix>.zerwiz.org. Nothing is invented: an app
# with no HTTP surface (the desktop shells) is listed as skipped, not faked.
set -u

VERSION="1.0.0"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
TUNNEL="${YMIR_TUNNEL_NAME:-ymir}"
DOMAIN="${YMIR_TUNNEL_DOMAIN:-zerwiz.org}"
SUFFIX="${YMIR_TUNNEL_SUFFIX:-dell}"
CONFIG="${YMIR_TUNNEL_CONFIG:-$HOME/.cloudflared/config-$TUNNEL.yml}"

have() { command -v "$1" >/dev/null 2>&1; }
up() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

case "${1:-plan}" in
  -v|-V|--version) printf '%s\n' "$VERSION"; exit 0 ;;
  -h|--help|"") sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
esac
ACTION="${1:-plan}"

# Every public hostname points at the GATE (:3889), never at an app's own port:
# the gate holds the login and proxies on by host, so the web door is locked for
# every app. An app port here would be a hole straight past the login.
GATE_PORT="${HLIDSKJALF_API_PORT:-3889}"
APPS=(
  "ymir:$GATE_PORT"
  "hlidskjalf:$GATE_PORT"
  "odrerir:$GATE_PORT"
  "smidja:$GATE_PORT"
  "smidjafactory:$GATE_PORT"
)

if [ -z "$SUFFIX" ]; then
  printf 'gjallarhorn[1]{step,status,detail}:\n'
  printf '  "expose","SKIP","no YMIR_TUNNEL_SUFFIX — this is not the dev machine; the server does not wear its names"\n'
  exit 0
fi

plan() {
  printf 'gjallarhorn_expose[%d]{host,port,state}:\n' "${#APPS[@]}"
  for row in "${APPS[@]}"; do
    local app="${row%%:*}" port="${row##*:}"
    printf '  "%s%s.%s","%s","%s"\n' "$app" "$SUFFIX" "$DOMAIN" "$port" \
      "$(up "$port" && printf up || printf down)"
  done
  printf 'gjallarhorn_skipped[2]{app,reason}:\n'
  printf '  "sessrumnir","electron desktop shell — no HTTP surface to expose"\n'
  printf '  "hlidskjalf-mobile","Expo app — installed on a phone, not served"\n'
}

case "$ACTION" in
  plan|status) plan; exit 0 ;;
  apply) : ;;
  *) printf 'error: unknown action %s\nhelp: bin/gjallarhorn-expose.sh [plan|apply|status]\n' "$ACTION" >&2; exit 2 ;;
esac

have cloudflared || { printf 'error: cloudflared not found\nhelp: install cloudflared, then re-run\n' >&2; exit 1; }

# 1. the config: one ingress rule per app that actually answers
mkdir -p "$(dirname "$CONFIG")"
{
  printf '# Gjallarhorn — this machine (%s). Generated by bin/gjallarhorn-expose.sh.\n' "$SUFFIX"
  printf 'tunnel: %s\n' "$TUNNEL"
  # No credentials-file line: cloudflared resolves <UUID>.json for a named
  # tunnel itself. Guessing the filename (ymir.json) is what made it refuse to
  # start, and a tunnel that will not start answers 530 to the world.
  printf 'ingress:\n'
  for row in "${APPS[@]}"; do
    app="${row%%:*}"; port="${row##*:}"
    printf '  - hostname: %s%s.%s\n    service: http://127.0.0.1:%s\n' "$app" "$SUFFIX" "$DOMAIN" "$port"
  done
  printf '  - service: http_status:404\n'
} >"$CONFIG"

# 2. the routes (idempotent: an existing record is left alone)
# Route by the tunnel's own UUID, never by its name. `route dns <name> <host>`
# resolves the name through the account certificate, which can point at a
# DIFFERENT (even deleted) tunnel: every hostname then answers 530 while the
# named tunnel runs happily beside it. Resolve the UUID first, then route.
TUNNEL_ID="$(cloudflared tunnel info "$TUNNEL" 2>/dev/null | grep -m1 -oE '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}')"
[ -n "$TUNNEL_ID" ] || TUNNEL_ID="$TUNNEL"
made=0
for row in "${APPS[@]}"; do
  app="${row%%:*}"
  cloudflared tunnel route dns --overwrite-dns "$TUNNEL_ID" "$app$SUFFIX.$DOMAIN" >/dev/null 2>&1 && made=$((made+1))
done

# 2b. the gate must know which host belongs to which app (it routes by host)
HOSTMAP="$ROOT/state/gjallarhorn-hosts.env"
{
  printf '# Written by bin/gjallarhorn-expose.sh — the gate routes these hosts.\n'
  printf 'SMIDJA_HOST=smidja%s.%s\n' "$SUFFIX" "$DOMAIN"
  printf 'ODRERIR_HOST=odrerir%s.%s\n' "$SUFFIX" "$DOMAIN"
} >"$HOSTMAP"

# 3. raise it
started="already"
if ! pgrep -f "cloudflared.*tunnel.*--config $CONFIG" >/dev/null 2>&1; then
  nohup cloudflared tunnel --config "$CONFIG" run "$TUNNEL" >"$ROOT/state/gjallarhorn.log" 2>&1 &
  started="pid $!"
  sleep 4
fi

printf 'gjallarhorn_apply[3]{what,detail,count}:\n'
printf '  "config","%s","%s"\n' "${CONFIG#"$HOME"/}" "${#APPS[@]}"
printf '  "routes","%s%s.%s","%s"\n' "" "$SUFFIX" "$DOMAIN" "$made"
printf '  "hostmap","%s","the gate routes by host"\n' "${HOSTMAP#"$ROOT"/}"
printf '  "tunnel","%s","%s"\n' "$started" "$TUNNEL"
plan
