// Generates src/avatar/characters.gen.ts from artwork/characters/*.svg (plan 275, 2026-11-13).
// The house's fourteen characters, one for each figure of the lore, drawn from game-icons.net (CC BY 3.0;
// credits in THIRD_PARTY_NOTICES.md). Each source is a 512×512 SVG: a black background square and the figure in
// white. Only the figure's paths are kept; the avatar paints them in the Ymir mark's bronze on stone.
import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve(import.meta.dirname, '../artwork/characters');
// order = the picker's order; name = what the person sees; source = the artist's file, for the credit
const CHARACTERS = [
  ['huginn', 'Huginn · the raven', 'lorc/raven'],
  ['fenrir', 'Fenrir · the wolf', 'lorc/wolf-head'],
  ['jormungandr', 'Jörmungandr · the serpent', 'lorc/ouroboros'],
  ['sleipnir', 'Sleipnir · the horse', 'lorc/horse-head'],
  ['ratatoskr', 'Ratatoskr · the squirrel', 'delapouite/squirrel'],
  ['hraesvelgr', 'Hræsvelgr · the eagle', 'lorc/eagle-emblem'],
  ['heidrun', 'Heiðrún · the goat', 'skoll/goat'],
  ['eikthyrnir', 'Eikþyrnir · the stag', 'lorc/stag-head'],
  ['gullinbursti', 'Gullinbursti · the boar', 'caro-asercion/boar'],
  ['mjolnir', 'Mjölnir · the hammer', 'delapouite/thor-hammer'],
  ['gungnir', 'Gungnir · the spear', 'delapouite/spear-feather'],
  ['skidbladnir', 'Skíðblaðnir · the ship', 'delapouite/drakkar'],
  ['sol', 'Sól · the sun', 'caro-asercion/heraldic-sun'],
  ['mani', 'Máni · the moon', 'lorc/moon'],
];
const out = [];
for (const [id, name, source] of CHARACTERS) {
  const svg = fs.readFileSync(path.join(dir, `${id}.svg`), 'utf8');
  const ds = [...svg.matchAll(/<path([^>]*)\sd="([^"]+)"/g)]
    .filter(([, attrs, d]) => !/^M0 0h512v512H0z$/i.test(d.trim()) && !/fill="#000"/i.test(attrs))
    .map(([, , d]) => d);
  if (!ds.length) throw new Error(`no figure path in ${id}.svg`);
  out.push({ id, name, source, d: ds.join(' ') });
}
const ts = `// AUTO-GENERATED by scripts/gen-characters.mjs from web/artwork/characters. Do not edit.
export interface CharacterDef { id: string; name: string; source: string; d: string }
export const CHARACTERS: CharacterDef[] = ${JSON.stringify(out)};
export const CHARACTER_BY_ID: Record<string, CharacterDef> = Object.fromEntries(CHARACTERS.map((c) => [c.id, c]));
`;
fs.writeFileSync(path.resolve(import.meta.dirname, '../src/avatar/characters.gen.ts'), ts);
console.log(`characters.gen.ts: ${out.length} characters`);
